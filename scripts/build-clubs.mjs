// Generates the club layer for both sports:
//   src/data/clubs.football.js    from the EA Sports FC player export
//   src/data/clubs.basketball.js  from the built-in season's NBA 2K ratings, as 2K Archive compiles them
//
//   npm run build-clubs
//
// Clubs are combatants in their own right, so each needs the same shape a nation
// has: an id, a short code, a colour, a strength and a lineup. They also carry a
// home country, which is what seeds them onto the map.

import { readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { NATIONS } from '../src/data/teams.js';
import { TOP_CLUBS } from '../src/data/scopes.js';
import { EUROPE_MAPS } from '../src/data/europeMaps.js';
import { BUILT_IN_SEASON } from '../src/engine/footballSets.js';
import { loadEaPlayers } from './lib/football-data.mjs';
import { clubsModule } from './lib/data-module.mjs';
import { colourFor, makeCode } from './lib/club-identity.mjs';
import { EA_CLUB_SNAPSHOT, firstDivisionClubs, squadTuples } from './lib/first-divisions.mjs';
import { clubRows, countryMapClubs, todayField, todayMapTag } from './lib/today-field.mjs';
import { nbaSeasonClubs, readArchive } from './lib/nba-seasons.mjs';
import { CLUBS as CURRENT_NBA_CLUBS } from '../src/data/clubs.basketball.js';
import { CLUBS as CURRENT_FOOTBALL_CLUBS } from '../src/data/clubs.football.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const FOOTBALL_FORMATION = { GK: 1, DF: 4, MF: 4, FW: 2 };

function parseCsv(text) {
  const rows = [];
  let field = '';
  let row = [];
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

/** clubs.basketball.js: each club's five as `[name, 'PG/SG', rating]`, one club a line. */
function emit(clubs, file, header) {
  const body = clubs
    .map(c => {
      const players = c.squad.map(([name, positions, rating]) => `[${JSON.stringify(name)},'${positions}',${rating}]`).join(',');
      return `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: ${JSON.stringify(c.league)}, country: '${c.country}', col: '${c.col}', str: ${c.str}, squad: [${players}] },`;
    })
    .join('\n');
  return writeFile(path.join(root, 'src', 'data', file), `${header}\nexport const CLUBS = [\n${body}\n];\n`);
}

// ---------------- football ----------------

const eaSource = process.argv[2] || EA_CLUB_SNAPSHOT;
const { players: eaPlayers } = await loadEaPlayers(eaSource);

// Europe's TOP_CLUBS strongest clubs by results (scripts/lib/today-field.mjs): the newest season the results rank
// (scripts/data/club-strength.json), each club with its EA FC 27 XI, or, in a country whose first division EA does not
// rate whole, the XI of the FM 26 squad today's country map gives it. After them, unranked, every club a built-in Europe
// map of before holds (its saves resume on it) that the field no longer does. A club keeps the code it had.
const strengthDoc = JSON.parse(readFileSync(path.join(root, 'scripts/data/club-strength.json'), 'utf8'));
const newest = Math.max(...Object.keys(strengthDoc.seasons).map(Number));
const { names } = JSON.parse(readFileSync(path.join(root, 'scripts/data/club-strength-names.json'), 'utf8'));
const fielded = firstDivisionClubs(eaPlayers);
const today = todayField({ strengths: strengthDoc.seasons[newest], names, ea: fielded, maps: countryMapClubs(root), count: TOP_CLUBS });
// Every built-in Europe map but today's own two (eu124b2027): today's maps of before, whatever the index yet says of them.
const before = EUROPE_MAPS.filter(entry => entry.sport === 'football' && entry.seasons == null && !entry.id.endsWith(todayMapTag(BUILT_IN_SEASON.year)))
  .flatMap(entry => JSON.parse(readFileSync(path.join(root, 'public/domestic', `${entry.id}.json`), 'utf8')).clubs.map(club => club.id));
const footballClubs = clubRows({ field: today.clubs, ea: fielded, kept: [...new Set(before)],
  codes: new Map(CURRENT_FOOTBALL_CLUBS.map(club => [club.id, club.code])), makeCode, colourFor, squadTuples, year: BUILT_IN_SEASON.year });

// The football clubs carry full source metadata, so they are stored compactly (scripts/lib/data-module.mjs).
await writeFile(path.join(root, 'src', 'data', 'clubs.football.js'), clubsModule(
  footballClubs,
  `// GENERATED by scripts/build-clubs.mjs from the committed ${eaPlayers[0].sourceInfo.edition} snapshot (${eaPlayers[0].sourceInfo.snapshotDate}),
// today's FM 26 country maps (public/domestic/) and the results (scripts/data/club-strength.json, season ending ${newest}).
// Player tuples retain database identity, all natural roles, original overall and source URL.
//
// Europe's ${TOP_CLUBS} strongest clubs by results (\`rank\`, 1 the strongest: scripts/lib/today-field.mjs), each with its
// best XI in a 4-4-2 and a strength equal to that lineup's mean rating: EA's where EA rates the club's league whole,
// else the club's FM 26 squad on its country map. Then, unranked, the clubs of today's Europe maps of before that the
// field no longer holds, kept so those maps still decode for the campaigns saved on them. \`country\` is the map shape
// the club holds its land in.
// Stored compactly: each line is JSON, and source metadata is a row under a
// shared shape (src/data/sourceTable.js).
`,
));

const field = footballClubs.filter(c => c.rank != null);
console.log(`football: ${field.length} clubs by results (season ending ${newest}), ${today.clubs.filter(c => c.source === 'fm').length} of them`
  + ` FM 26's, from ${new Set(field.map(c => c.country)).size} countries; ${footballClubs.length - field.length} more kept for the maps of before`);
const byCountry = new Map();
for (const c of field) byCountry.set(c.country, (byCountry.get(c.country) || 0) + 1);
console.log(`  ${[...byCountry].sort((a, b) => b[1] - a[1]).map(([country, n]) => `${NATIONS[country][0]} ${n}`).join(', ')}`);
console.log(`  EA rates whole: ${today.whole.map(country => NATIONS[country][0]).join(', ')}`);
if (today.passed.length) console.log(`  passed over (no first-division XI): ${today.passed.join('; ')}`);
console.log(`  strongest: ${field.slice(0, 6).map(c => `${c.name} ${c.str}`).join(', ')}`);

// ---------------- basketball ----------------

// The built-in season's NBA 2K, as 2K Archive lists each player's team, positions and overall: the pinned page the
// earlier seasons come from (scripts/data/nba-seasons.json, `builtIn`). Each franchise fields the strongest five its
// players' positions allow and keeps the code and colour it has.
const archive = await readArchive(root);
const nbaBuiltIn = archive.manifest.builtIn;
const nba = nbaSeasonClubs(archive.years, nbaBuiltIn.year, archive.manifest, { arenas: archive.arenas, builtIn: CURRENT_NBA_CLUBS });
const basketballClubs = nba.clubs;

await emit(
  basketballClubs,
  'clubs.basketball.js',
  `// GENERATED by scripts/build-clubs.mjs from ${nbaBuiltIn.edition}'s ratings (${nbaBuiltIn.season}), as ${archive.manifest.source.name} compiles them
// (scripts/data/nba-seasons.json).
//
// NBA franchises with their best starting five. Each player lists the positions 2K gives him, primary first
// ('PG/SG'; a second position that is not the first's neighbour is dropped), and each five is the strongest lineup
// the franchise's positions allow.
`,
);

console.log(`basketball: ${basketballClubs.length} franchises`);
console.log(`  strongest: ${basketballClubs.slice(0, 6).map(c => `${c.name} ${c.str}`).join(', ')}`);
const starters = basketballClubs.flatMap(c => c.squad);
console.log(`  ${starters.filter(([, positions]) => positions.includes('/')).length} of ${starters.length} starters cover two positions`);
for (const warning of nba.warnings) console.log(`  warning: ${warning}`);
