// Build Valorant's national teams from the committed vlr.gg Elo snapshot (scripts/data/valorant-elo.json,
// npm run sync:valorant) into src/data/rosters.valorant.js. The rules (ratings, nations, teams) are scripts/lib/valorant.mjs's.
//
// Usage: node scripts/build-valorant.mjs [--check]
//   npm run build-valorant
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { valorant } from '../src/sports/valorant.js';
import { leftOut, nationsOf } from './lib/esports-elo.mjs';
import { EDITION, LINEUP, TEAM_SIZE, playerOf, tupleOf } from './lib/valorant.mjs';

const args = process.argv.slice(2);
const unknown = args.filter(arg => arg !== '--check');
if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const snapshotFile = 'scripts/data/valorant-elo.json';
const rostersFile = path.join(root, 'src', 'data', 'rosters.valorant.js');
const snapshot = JSON.parse(await readFile(path.join(root, snapshotFile), 'utf8'));
const { source } = snapshot;

const players = snapshot.players.map((row, i) => playerOf(row, source.fetched, i + 1));
const nations = nationsOf(players, { teamSize: TEAM_SIZE, lineup: LINEUP, sport: valorant });
const tuple = player => JSON.stringify(tupleOf(player));
const SOURCE = { name: 'vlr.gg', edition: EDITION, updated: source.fetched, from: source.from, to: source.to, matches: source.matches,
  maps: source.maps, rated: source.rated, url: source.site };

const rostersText = `// GENERATED by scripts/build-valorant.mjs from ${snapshotFile}; do not edit.
//
// The national teams of Valorant: every player rated by Elo from the maps vlr.gg records (${source.from} to ${source.to},
// ${source.maps} maps of VCT, Challengers and the off-season) who has played in the last ${source.activeDays} days, by the nation he
// last played for at the Esports Nations Cup, else the flag vlr.gg files him under, each nation's ${TEAM_SIZE} best. Each newcomer
// starts at his home circuit's level (docs/design/valorant.md, "Circuits on one scale"). A rating is the player's Elo / 25 − 2,
// rounded (scripts/lib/valorant.mjs). Each entry is [strength, players, squad]: the strength is the
// mean of the ${LINEUP} who play, and a nation with fewer than ${LINEUP} rated players is not here.

export const SOURCE = ${JSON.stringify(SOURCE)};

export const ROSTERS = {
${nations.map(n => `  '${n.id}': [${n.str},${n.squad.length},[${n.squad.map(tuple).join(',')}]], // ${n.name}`).join('\n')}
};
`;

if (args.includes('--check')) {
  const current = (await readFile(rostersFile, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== rostersText) {
    console.error(`differs: ${path.relative(root, rostersFile)}`);
    process.exit(1);
  }
  console.log('Verified the Valorant nations byte for byte.');
} else {
  await writeFile(rostersFile, rostersText);
  const { noNation, short } = leftOut(players, { lineup: LINEUP });
  console.log(`Wrote ${nations.length} nations to ${path.relative(root, rostersFile)} (vlr.gg Elo, ${source.from} to ${source.to})`);
  for (const n of nations) console.log(`  ${n.name} ${n.str}: ${n.squad.map(p => `${p.name} ${p.rating}`).join(', ')}${n.players > TEAM_SIZE ? ` (+${n.players - TEAM_SIZE})` : ''}`);
  console.log(`  left out: ${noNation.length} with no country on the map; ${short.length} from a nation of fewer than ${LINEUP}`);
}
