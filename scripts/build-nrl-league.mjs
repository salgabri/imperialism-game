// Build rugby league's scoring by era (docs/design/rugby-league.md, "Rules by era").
//
//   node scripts/build-nrl-league.mjs           writes src/data/nrlLeagueAverages.js
//   node scripts/build-nrl-league.mjs --check   builds it and compares it byte for byte, writes nothing
//
// Each built-in earlier season's tries, field goals and points a team a game (scripts/lib/nrl-league.mjs,
// `leagueFigures`): before 1998 from the Rugby League Project's season list in data-src/rugby-league-seasons/rlp/ (the
// one its ratings read, checked against its pin in scripts/data/rugby-league-seasons-sources.json; without the cache,
// node scripts/sync-rugby-league-seasons.mjs --fetch, the committed figures are kept), from 1998 from the NRL.com stats
// its snapshot keeps; the regular season's points from its snapshot. Then its scoring is solved on its clubs
// (public/rugby-league/<id>.json) under its own day's points and extra time (`solveScoring`).
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { cachedList, leagueFigures, seasonClubs, solveScoring } from './lib/nrl-league.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const moduleFile = path.join(root, 'src/data/nrlLeagueAverages.js');

const args = process.argv.slice(2);
const check = args.includes('--check');
const unknown = args.filter(arg => arg !== '--check');
if (unknown.length) throw new Error(`Unknown arguments: ${unknown.join(' ')}`);

const num = (x, places = 3) => String(Math.round(x * 10 ** places) / 10 ** places);

function moduleText(rows) {
  // Two lines a season: the league's figures, then the model's scoring.
  const line = ({ id, points, tries, fieldGoals, scoring }) => {
    const figures = tries == null ? '' : `, tries: ${num(tries)}, fieldGoals: ${num(fieldGoals)}`;
    const model = `tries: ${num(scoring.tries, 4)}, penalties: ${num(scoring.penalties, 4)}, fieldGoals: ${num(scoring.fieldGoals, 4)}, `
      + `openFieldGoals: ${num(scoring.openFieldGoals, 4)}`;
    return `  '${id}': Object.freeze({ points: ${num(points)}${figures},\n    scoring: Object.freeze({ ${model} }) }),`;
  };
  return `// GENERATED by node scripts/build-nrl-league.mjs; do not edit.
// Rugby league's scoring by season (docs/design/rugby-league.md, "Rules by era"), each built-in earlier season by its
// id: the points a team scored a game in its regular season (\`points\`, its snapshot's real season), and its tries and
// field goals a team a game over all its games, at its regular season's level (× its points over the whole season's).
// To 1997 from the Rugby League Project's season lists (each player's tries and field goals, the lists its ratings
// read), from 1998 from the NRL.com stats its snapshot keeps; 2008, rated by a game that keeps no stats, has its points
// alone. \`scoring\`: the match model's, not the league's (src/sports/rugbyLeague.js, \`rugbyLeagueIn\`), solved over every
// pairing of its clubs under its own day's points and extra time: \`tries\` scales the try rates to its tries,
// \`fieldGoals\` the late field-goal chances and \`openFieldGoals\` adds open play's to reach its field goals, and
// \`penalties\`, a side's penalty goals in eighty minutes between equals, makes up its points (conversions at today's
// rate); 2008 scales tries and penalty goals alike to its points. The built-in season, 2025, plays today's level: tries
// 1, penalties 0.39, field goals 1.
export const NRL_LEAGUE_AVERAGES = Object.freeze({
${rows.map(line).join('\n')}
});
`;
}

async function main() {
  const manifest = JSON.parse(await readFile(path.join(root, 'scripts/data/rugby-league-seasons.json'), 'utf8'));
  const { sources } = JSON.parse(await readFile(path.join(root, 'scripts/data/rugby-league-seasons-sources.json'), 'utf8'));
  const committed = existsSync(moduleFile) ? (await import(pathToFileURL(moduleFile).href)).NRL_LEAGUE_AVERAGES : {};
  const rows = [];
  let kept = 0;
  for (const entry of manifest.seasons.slice().sort((a, b) => a.year - b.year || a.id.localeCompare(b.id))) {
    const snapshot = JSON.parse(await readFile(path.join(root, `scripts/data/rugby-league-seasons/${entry.id}.json`), 'utf8'));
    let figures;
    if (snapshot.source.basis === 'selection') {
      const html = cachedList(root, entry.rlp.season, sources);
      if (html) figures = leagueFigures(snapshot, html);
      else if (committed[entry.id]?.tries != null) {
        const { points, tries, fieldGoals } = committed[entry.id];
        if (points !== snapshot.real.figures.pointsPerTeam) throw new Error(`${entry.id}: the committed points are not the snapshot's`);
        figures = { points, tries, fieldGoals, from: 'kept' };
        kept++;
      } else throw new Error(`${entry.id}: no RLP list in data-src/rugby-league-seasons/ and no committed figures: run node scripts/sync-rugby-league-seasons.mjs --fetch`);
    } else figures = leagueFigures(snapshot);
    const scoring = solveScoring(entry.id, entry.year, seasonClubs(root, entry.id), figures, { games: 16000 });
    rows.push({ id: entry.id, ...figures, scoring });
    console.log(`${entry.id}: ${figures.points} points, ${figures.tries ?? '—'} tries, ${figures.fieldGoals ?? '—'} field goals a team (${figures.from ?? 'points alone'})`
      + ` → tries ×${scoring.tries}, penalties ${scoring.penalties}, field goals ×${scoring.fieldGoals} + ${scoring.openFieldGoals} in open play`);
  }
  const text = moduleText(rows);
  if (kept) console.log(`Kept the committed figures of ${kept} season${kept === 1 ? '' : 's'} (their RLP lists are not on this computer).`);
  if (check) {
    const current = existsSync(moduleFile) ? (await readFile(moduleFile, 'utf8')).replace(/\r\n/g, '\n') : null;
    if (current !== text) throw new Error('differs: src/data/nrlLeagueAverages.js');
    console.log(`Verified src/data/nrlLeagueAverages.js byte for byte (${rows.length} seasons).`);
    return;
  }
  await writeFile(moduleFile, text);
  console.log(`Wrote src/data/nrlLeagueAverages.js (${rows.length} seasons).`);
}

main().catch(error => {
  console.error(`build-nrl-league: ${error.message}`);
  process.exitCode = 1;
});
