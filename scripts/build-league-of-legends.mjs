// Build League of Legends' national teams from the committed gol.gg Elo snapshot (scripts/data/league-of-legends-elo.json,
// npm run sync:league-of-legends) into src/data/rosters.league-of-legends.js. The rules (ratings, roles, nations, teams)
// are scripts/lib/league-of-legends.mjs's.
//
// Usage: node scripts/build-league-of-legends.mjs [--check]
//   npm run build-league-of-legends
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { leagueOfLegends } from '../src/sports/leagueOfLegends.js';
import { leftOut } from './lib/esports-elo.mjs';
import { EDITION, LINEUP, TEAM_SIZE, nationsOf, playerOf, tupleOf } from './lib/league-of-legends.mjs';

const args = process.argv.slice(2);
const unknown = args.filter(arg => arg !== '--check');
if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const snapshotFile = 'scripts/data/league-of-legends-elo.json';
const rostersFile = path.join(root, 'src', 'data', 'rosters.league-of-legends.js');
const snapshot = JSON.parse(await readFile(path.join(root, snapshotFile), 'utf8'));
const { source } = snapshot;

const players = snapshot.players.map((row, i) => playerOf(row, source.fetched, i + 1));
const nations = nationsOf(players, leagueOfLegends);
const tuple = player => JSON.stringify(tupleOf(player));
const SOURCE = { name: 'gol.gg', edition: EDITION, updated: source.fetched, from: source.from, to: source.to, series: source.series,
  games: source.games, rated: source.rated, url: source.site };

const rostersText = `// GENERATED by scripts/build-league-of-legends.mjs from ${snapshotFile}; do not edit.
//
// The national teams of League of Legends: every player rated by Elo from the games gol.gg records (${source.from} to
// ${source.to}, ${source.games} games) who has played in the last ${source.activeDays} days, by the country gol.gg files him under, in the
// role he plays most. Each nation names its best player in each role, then its best others, ${TEAM_SIZE} in all. A rating is the
// player's (Elo − 100) / 25, rounded (scripts/lib/league-of-legends.mjs). Each entry is [strength, players, squad]: the strength is
// its lineup's, one player a role (one out of his role plays below his rating), and a nation with fewer than ${LINEUP} rated
// players is not here.

export const SOURCE = ${JSON.stringify(SOURCE)};

export const ROSTERS = {
${nations.map(n => `  '${n.id}': [${n.str},${n.squad.length},[${n.squad.map(tuple).join(',')}]], // ${n.name}`).join('\n')}
};
`;

if (args.includes('--check')) {
  const current = (await readFile(rostersFile, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== rostersText) {
    console.error(`differs: ${path.relative(root, rostersFile)}`);
    process.exit(1);
  }
  console.log('Verified the League of Legends nations byte for byte.');
} else {
  await writeFile(rostersFile, rostersText);
  const { noNation, short } = leftOut(players, { lineup: LINEUP });
  console.log(`Wrote ${nations.length} nations to ${path.relative(root, rostersFile)} (gol.gg Elo, ${source.from} to ${source.to})`);
  for (const n of nations) console.log(`  ${n.name} ${n.str}: ${n.squad.map(p => `${p.name} ${p.role} ${p.rating}`).join(', ')}${n.players > TEAM_SIZE ? ` (+${n.players - TEAM_SIZE})` : ''}`);
  console.log(`  left out: ${noNation.length} with no country on the map; ${short.length} from a nation of fewer than ${LINEUP}`);
}
