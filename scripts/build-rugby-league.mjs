// Build rugby league's teams from the committed NRL snapshot (scripts/data/rugby-league-26.json, npm run sync:nrl): the
// 17 NRL clubs (src/data/clubs.rugby-league.js, named from scripts/data/nrl-teams.json) and the national teams
// (src/data/rosters.rugby-league.js). The rules (positions, lineups, depth, nations) are scripts/lib/nrl.mjs's.
//
// Usage: node scripts/build-rugby-league.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { colourFor } from './lib/club-identity.mjs';
import { clubsOf, nationsOf, playerOf, tupleOf } from './lib/nrl.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const clubsFile = path.join(root, 'src/data/clubs.rugby-league.js');
const rostersFile = path.join(root, 'src/data/rosters.rugby-league.js');
const snapshot = JSON.parse(await readFile(path.join(root, 'scripts/data/rugby-league-26.json'), 'utf8'));
const { teams } = JSON.parse(await readFile(path.join(root, 'scripts/data/nrl-teams.json'), 'utf8'));
const { source } = snapshot;

const players = snapshot.players.map(playerOf);
const clubs = clubsOf(players, teams);
const rosters = nationsOf(players);
const tuple = p => JSON.stringify(tupleOf(p));
const SOURCE = { edition: 'Rugby League 26', season: '2025', published: source.published, retrieved: source.retrieved, url: source.ratings };
// The Warriors are New Zealand's; every other club is Australia's.
const countryOf = id => (id === 'nrl-new-zealand-warriors' ? '554' : '036');

const clubsText = `// GENERATED by scripts/build-rugby-league.mjs from scripts/data/rugby-league-26.json; do not edit.
//
// The 17 NRL clubs as Rugby League 26 (Big Ant Studios) rates them, in the list Zero Tackle published on the game's
// release, ${source.published}: each fields the matchday 17 the game picks from its whole list (the thirteen and an
// interchange bench of a hooker, two props and a lock), then its best players left, up to 24. Ratings are the game's
// overalls, unchanged; positions are Zero Tackle's and those each player started in the 2025 NRL season (NRL.com).

export const SOURCE = ${JSON.stringify(SOURCE)};

export const CLUBS = [
${clubs.map(c => `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: 'NRL', country: '${countryOf(c.id)}', col: '${colourFor(c.id)}', str: ${c.str}, squad: [${c.squad.map(tuple).join(',')}] },`).join('\n')}
];
`;
const rostersText = `// GENERATED by scripts/build-rugby-league.mjs from scripts/data/rugby-league-26.json; do not edit.
//
// National teams of the NRL's players, Rugby League 26's ratings as in src/data/clubs.rugby-league.js: each plays for the
// nation he played a Test for in 2025, else for the country he was born in, else for the first nation on the map he is
// eligible for. Each entry is [strength, realCount, squad], where squad is the matchday 17 the game picks from the
// nation's players, then up to a club's depth, and strength counts a place no player of the nation can fill at the
// sport's baseline; the game fields a generated player there.

export const ROSTERS = {
${rosters.map(r => `  '${r.id}': [${r.str},${r.squad.length},[${r.squad.map(tuple).join(',')}]], // ${r.name}`).join('\n')}
};
`;

if (process.argv.includes('--check')) {
  let differs = false;
  for (const [file, text] of [[clubsFile, clubsText], [rostersFile, rostersText]]) {
    const current = (await readFile(file, 'utf8')).replace(/\r\n/g, '\n');
    if (current !== text) { console.error(`differs: ${path.relative(root, file)}`); differs = true; }
  }
  if (differs) process.exit(1);
  console.log('Verified the NRL clubs and the rugby league nations byte for byte.');
} else {
  await writeFile(clubsFile, clubsText);
  await writeFile(rostersFile, rostersText);
  console.log(`Wrote ${clubs.length} NRL clubs to ${path.relative(root, clubsFile)}`);
  for (const c of clubs) console.log(`  ${c.name.padEnd(30)} ${c.str}  (${c.squad.length} players)`);
  const homeless = players.filter(p => p.nation == null);
  console.log(`Wrote ${rosters.length} nations to ${path.relative(root, rostersFile)}; ${homeless.length} players play for no nation`
    + ` (${[...new Set(homeless.map(p => p.test || p.birthplace))].join(', ')})`);
  for (const r of rosters) console.log(`  ${r.name.padEnd(20)} ${r.str}: ${r.squad.length} players${r.open.length ? `, the game fills ${r.open.join(' ')}` : ''}`);
}
