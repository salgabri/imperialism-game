// Build the NFL clubs (src/data/clubs.american-football.js) from the committed Madden NFL snapshot
// (scripts/data/madden-nfl-27.json, npm run sync:madden) and the franchise table (scripts/data/nfl-teams.json).
//
// Madden lists one position per player, finer than the game's: its five line spots become OL, the edges and tackles
// DL, its three linebackers LB, both safeties S and the fullback RB. Punters and long snappers have no place in the
// lineup and are left out. Each franchise fields the lineup the game itself picks from its whole roster (eleven on
// offence, the nickel defence and the kicker), then the best backups at each position. Ratings are Madden's overalls,
// unchanged. The squad rules are scripts/lib/nfl.mjs's, which the earlier seasons (scripts/build-nfl-seasons.mjs) share.
//
// Usage: node scripts/build-nfl.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { colourFor, playerOf, squadOf, strongestFirst } from './lib/nfl.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const snapshotFile = path.join(root, 'scripts/data/madden-nfl-27.json');
const teamsFile = path.join(root, 'scripts/data/nfl-teams.json');
const outFile = path.join(root, 'src/data/clubs.american-football.js');

const snapshot = JSON.parse(await readFile(snapshotFile, 'utf8'));
const franchises = JSON.parse(await readFile(teamsFile, 'utf8')).teams;
const byEa = new Map(Object.entries(franchises).map(([id, team]) => [String(team.ea), { id, ...team }]));
for (const [ea, label] of Object.entries(snapshot.teams)) {
  const team = byEa.get(ea);
  // EA shortens the two New York teams to "NY Giants" and "NY Jets".
  if (!team || team.name !== label.replace(/^NY /, 'New York ')) throw new Error(`EA team ${ea} (${label}) is not in nfl-teams.json`);
}
if (byEa.size !== Object.keys(snapshot.teams).length) throw new Error('nfl-teams.json lists a team the snapshot does not have');

const pools = new Map();
for (const [, name, ea, listed, overall] of snapshot.players) {
  const player = playerOf(name, listed, overall);
  if (!player) continue;
  if (!pools.has(String(ea))) pools.set(String(ea), []);
  pools.get(String(ea)).push(player);
}

const clubs = [...byEa.values()].map(team => {
  const { squad, str } = squadOf(pools.get(String(team.ea)) || [], team.name);
  return { id: team.id, name: team.name, code: team.code, league: 'NFL', country: '840', col: colourFor(team.id), str, squad };
}).sort(strongestFirst);

const { source } = snapshot;
const text = `// GENERATED by scripts/build-nfl.mjs from scripts/data/madden-nfl-27.json; do not edit.
//
// The 32 NFL franchises of ${source.edition} (${source.iteration.label}, retrieved ${source.retrieved} from EA SPORTS'
// ratings site). Each fields the lineup the game picks from its whole roster — QB, RB, three WR, TE and five OL; four
// DL, two LB, three CB and two S; the kicker — then its best backups. Madden's positions are grouped into the game's
// (its five line spots are OL, edges and tackles DL); ratings are Madden's overalls, unchanged.

export const SOURCE = ${JSON.stringify({ edition: source.edition, season: source.season, update: source.iteration.label, retrieved: source.retrieved, url: source.url })};

export const CLUBS = [
${clubs.map(c => `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: 'NFL', country: '840', col: '${c.col}', str: ${c.str}, squad: [${c.squad.map(p => `[${JSON.stringify(p.name)},'${p.pos}',${p.rating}]`).join(',')}] },`).join('\n')}
];
`;

if (process.argv.includes('--check')) {
  const current = (await readFile(outFile, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== text) { console.error(`differs: ${path.relative(root, outFile)}`); process.exit(1); }
  console.log('Verified the NFL clubs byte for byte.');
} else {
  await writeFile(outFile, text);
  console.log(`Wrote ${clubs.length} NFL franchises to ${path.relative(root, outFile)}`);
  console.log(`  strongest: ${clubs.slice(0, 6).map(c => `${c.name} ${c.str}`).join(', ')}`);
  console.log(`  weakest: ${clubs.slice(-4).map(c => `${c.name} ${c.str}`).join(', ')}`);
}
