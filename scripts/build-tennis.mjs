// Build tennis's national teams from the committed Tennis Abstract snapshot (scripts/data/tennis-elo.json, npm run
// sync:tennis) into src/data/rosters.tennis.js. The rules (ratings, nations, teams) are scripts/lib/tennis.mjs's.
//
// Usage: node scripts/build-tennis.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { EDITION, leftOut, nationsOf, playerOf, TEAM_SIZE, tupleOf } from './lib/tennis.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const rostersFile = path.join(root, 'src/data/rosters.tennis.js');
const snapshot = JSON.parse(await readFile(path.join(root, 'scripts/data/tennis-elo.json'), 'utf8'));
const { source } = snapshot;

const players = snapshot.players.map(row => playerOf(row, source.updated));
const nations = nationsOf(players);
const tuple = player => JSON.stringify(tupleOf(player));
const SOURCE = { name: `${source.name} (${source.author})`, edition: EDITION, updated: source.updated, retrieved: source.retrieved,
  rated: source.players, url: source.elo };

const rostersText = `// GENERATED by scripts/build-tennis.mjs from scripts/data/tennis-elo.json; do not edit.
//
// The national teams of tennis: every man ${source.name} rates by Elo (${source.updated}), by the country it files him
// under, each nation's ${TEAM_SIZE} best as a Davis Cup captain nominates them. A rating is the player's Elo / 25 + 4,
// rounded (scripts/lib/tennis.mjs). Each entry is [strength, players, squad]: the strength is the lineup's (the No. 1 and
// No. 2 in the singles, the next two in the doubles), and a nation with fewer than two rated players is not here.

export const SOURCE = ${JSON.stringify(SOURCE)};

export const ROSTERS = {
${nations.map(n => `  '${n.id}': [${n.str},${n.squad.length},[${n.squad.map(tuple).join(',')}]], // ${n.name}`).join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = (await readFile(rostersFile, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== rostersText) {
    console.error(`differs: ${path.relative(root, rostersFile)}`);
    process.exit(1);
  }
  console.log('Verified the tennis nations byte for byte.');
} else {
  await writeFile(rostersFile, rostersText);
  const { unranked, offMap, alone } = leftOut(players);
  console.log(`Wrote ${nations.length} nations to ${path.relative(root, rostersFile)} (${source.name} Elo of ${source.updated})`);
  for (const n of nations) console.log(`  ${n.name} ${n.str}: ${n.squad.map(p => `${p.name} ${p.rating}`).join(', ')}${n.players > TEAM_SIZE ? ` (+${n.players - TEAM_SIZE})` : ''}`);
  console.log(`  left out: ${unranked.length} the ATP no longer ranks (${unranked.map(p => p.name).join(', ')}); ${offMap.length} from a country off the map (${offMap.map(p => `${p.name} ${p.country}`).join(', ')}); ${alone.length} his nation's only player (${alone.map(p => `${p.name} ${p.country}`).join(', ')})`);
}
