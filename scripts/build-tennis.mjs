// Build a tour's national teams from its committed Tennis Abstract snapshot: the men's (scripts/data/tennis-elo.json,
// npm run sync:tennis) into src/data/rosters.tennis.js, the women's (scripts/data/womens-tennis-elo.json, npm run
// sync:womens-tennis) into src/data/rosters.womens-tennis.js. The rules (ratings, nations, teams) are
// scripts/lib/tennis.mjs's.
//
// Usage: node scripts/build-tennis.mjs [--tour=atp|wta] [--check]
//   npm run build-tennis (the men's), npm run build-womens-tennis (the women's)
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { EDITION, leftOut, nationsOf, playerOf, TEAM_SIZE, tourOf, tupleOf } from './lib/tennis.mjs';

const args = process.argv.slice(2);
const unknown = args.filter(arg => arg !== '--check' && !/^--tour=/.test(arg));
if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);
const tour = tourOf(args.find(arg => arg.startsWith('--tour='))?.slice('--tour='.length) ?? 'atp');
const women = tour.id === 'wta';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const rostersFile = path.join(root, tour.rosters);
const snapshotFile = tour.snapshot;
const snapshot = JSON.parse(await readFile(path.join(root, snapshotFile), 'utf8'));
const { source } = snapshot;

const players = snapshot.players.map(row => playerOf(row, source.updated, tour));
const nations = nationsOf(players, tour);
const tuple = player => JSON.stringify(tupleOf(player));
const SOURCE = { name: `${source.name} (${source.author})`, edition: EDITION, updated: source.updated, retrieved: source.retrieved,
  rated: source.players, url: source.elo };

// The men's header is as it was before the women's tour joined, so their file rebuilds byte for byte.
const header = women
  ? `// GENERATED by scripts/build-tennis.mjs --tour=wta from ${snapshotFile}; do not edit.
//
// The national teams of women's tennis: every woman ${source.name} rates by Elo (${source.updated}), by the country it
// files her under, each nation's ${TEAM_SIZE} best as a Billie Jean King Cup captain nominates them. A rating is the
// player's Elo / 25 + 4, rounded (scripts/lib/tennis.mjs). Each entry is [strength, players, squad]: the strength is the
// lineup's (the No. 1 and No. 2 in the singles, the next two in the doubles), and a nation with fewer than two rated
// players is not here.`
  : `// GENERATED by scripts/build-tennis.mjs from ${snapshotFile}; do not edit.
//
// The national teams of tennis: every man ${source.name} rates by Elo (${source.updated}), by the country it files him
// under, each nation's ${TEAM_SIZE} best as a Davis Cup captain nominates them. A rating is the player's Elo / 25 + 4,
// rounded (scripts/lib/tennis.mjs). Each entry is [strength, players, squad]: the strength is the lineup's (the No. 1 and
// No. 2 in the singles, the next two in the doubles), and a nation with fewer than two rated players is not here.`;

const rostersText = `${header}

export const SOURCE = ${JSON.stringify(SOURCE)};

export const ROSTERS = {
${nations.map(n => `  '${n.id}': [${n.str},${n.squad.length},[${n.squad.map(tuple).join(',')}]], // ${n.name}`).join('\n')}
};
`;

if (args.includes('--check')) {
  const current = (await readFile(rostersFile, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== rostersText) {
    console.error(`differs: ${path.relative(root, rostersFile)}`);
    process.exit(1);
  }
  console.log(`Verified the ${women ? 'women\'s ' : ''}tennis nations byte for byte.`);
} else {
  await writeFile(rostersFile, rostersText);
  const { unranked, offMap, alone } = leftOut(players);
  console.log(`Wrote ${nations.length} nations to ${path.relative(root, rostersFile)} (${source.name} ${tour.name} Elo of ${source.updated})`);
  for (const n of nations) console.log(`  ${n.name} ${n.str}: ${n.squad.map(p => `${p.name} ${p.rating}`).join(', ')}${n.players > TEAM_SIZE ? ` (+${n.players - TEAM_SIZE})` : ''}`);
  console.log(`  left out: ${unranked.length} the ${tour.name} no longer ranks (${unranked.map(p => p.name).join(', ')}); ${offMap.length} from a country off the map or a combined team (${offMap.map(p => `${p.name} ${p.country}`).join(', ')}); ${alone.length} ${tour.pronoun} nation's only player (${alone.map(p => `${p.name} ${p.country}`).join(', ')})`);
}
