// Build the EuroLeague's clubs from the committed snapshot (scripts/data/euroleague-2026-27.json, npm run sync:euroleague)
// and their identities (scripts/data/euroleague-teams.json): src/data/clubs.euroleague.js, each club with its best five,
// and docs/design/euroleague-audit.json, every rostered player's estimate. The rules are scripts/lib/euroleague.mjs's.
// Then the earlier seasons' (scripts/data/euroleague-seasons/, npm run sync:euroleague-seasons): their league figures,
// src/data/euroleagueLeagueAverages.js, which each season's EuroLeague plays at (src/sports/basketball.js), and
// docs/design/euroleague-seasons-audit.json, each season's clubs and fives (scripts/lib/euroleague-seasons.mjs). Their
// clubs ride in the NBA seasons' files (npm run build:nba-seasons) and play on maps of their own (build-europe-maps.mjs).
//
// Usage: node scripts/build-euroleague.mjs [--check]
//   --check  rebuild and compare every file byte for byte; write nothing
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { colourFor } from './lib/club-identity.mjs';
import { euroleagueClubs, LEVEL_PIR, PRIOR_GAMES, PRIOR_PIR, RATING_AT_LEVEL, RATING_PER_PIR, RATING_RANGE, SEASON_WEIGHTS } from './lib/euroleague.mjs';
import { REFERENCE_SEASON, euroleagueSeasons, seasonScale, spearman } from './lib/euroleague-seasons.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const clubsFile = path.join(root, 'src/data/clubs.euroleague.js');
const auditFile = path.join(root, 'docs/design/euroleague-audit.json');
const averagesFile = path.join(root, 'src/data/euroleagueLeagueAverages.js');
const seasonsAuditFile = path.join(root, 'docs/design/euroleague-seasons-audit.json');
const check = process.argv.includes('--check');
const unknown = process.argv.slice(2).filter(arg => arg !== '--check');
if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);

const snapshot = JSON.parse(await readFile(path.join(root, 'scripts/data/euroleague-2026-27.json'), 'utf8'));
const identity = JSON.parse(await readFile(path.join(root, 'scripts/data/euroleague-teams.json'), 'utf8'));
const teams = Object.fromEntries(Object.entries(identity.clubs).map(([code, team]) => [code, { ...team, col: colourFor(team.id) }]));
const { clubs, players, warnings } = euroleagueClubs(snapshot, teams, identity.names);
const { source } = snapshot;

const SOURCE = { name: source.label, retrieved: source.retrieved, url: 'https://www.euroleaguebasketball.net/', api: source.api };
const tuple = ([name, positions, rating, metadata]) => `[${JSON.stringify(name)},'${positions}',${rating},${JSON.stringify(metadata)}]`;
const clubsText = `// GENERATED by scripts/build-euroleague.mjs from scripts/data/euroleague-2026-27.json; do not edit.
//
// The ${clubs.length} clubs of the ${source.label} on their rosters of ${source.retrieved}, each with its best starting five: the
// strongest lineup its players' positions allow. No source rates EuroLeague players, so every rating is the game's
// estimate on NBA 2K's scale from the player's EuroLeague box scores (his PIR a game, ${source.seasons.join(', ')}), marked
// as one (scripts/lib/euroleague.mjs, docs/design/euroleague.md). Basketball's clubs are the NBA's
// (src/data/clubs.basketball.js) and these; the two leagues never meet.

export const SOURCE = ${JSON.stringify(SOURCE)};

export const CLUBS = [
${clubs.map(c => `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: 'EuroLeague', country: '${c.country}', col: '${c.col}', str: ${c.str}, squad: [${c.squad.map(tuple).join(',')}] },`).join('\n')}
];
`;

const fixed = (value, digits = 2) => Number(value.toFixed(digits));
const starters = new Set(clubs.flatMap(c => c.squad.map(p => `${c.source}|${p[0]}`)));
const audit = {
  note: 'Every player on a EuroLeague roster as the game rates him (scripts/build-euroleague.mjs): his PIR a game over the seasons, as weighted and shrunk, the rating that gives, the positions the box score and height give, and whether he starts for his club. Regenerated with the clubs; the rule is in docs/design/euroleague.md.',
  source: { label: source.label, retrieved: source.retrieved, seasons: source.seasons },
  rule: { levelPir: LEVEL_PIR, ratingAtLevel: RATING_AT_LEVEL, ratingPerPir: RATING_PER_PIR, range: RATING_RANGE, seasonWeights: SEASON_WEIGHTS,
    priorPir: PRIOR_PIR, priorGames: PRIOR_GAMES },
  league: snapshot.league,
  clubs: clubs.map(c => ({ id: c.id, name: c.name, str: c.str, five: c.squad.map(([name, positions, rating]) => `${name} ${positions} ${rating}`) })),
  players: players.slice().sort((a, b) => b.rating - a.rating || b.pir - a.pir || a.name.localeCompare(b.name))
    .map(p => ({ code: p.code, club: teams[p.club].name, name: p.name, positions: p.positions.join('/'), rating: p.rating, pir: fixed(p.pir),
      games: p.games, ...(starters.has(`${p.club}|${p.name}`) ? { starts: true } : {}) })),
  warnings,
};
const auditText = `${JSON.stringify(audit, null, 1)}\n`;

// ---------- the earlier seasons ----------

const earlier = euroleagueSeasons(root, identity);
const seasonOf = year => `${year}/${String(year + 1).slice(2)}`;
const averageRow = ({ year }) => {
  const { pace, rating, points } = earlier.snapshots[year].league;
  return `  '${seasonOf(year)}': Object.freeze({ pace: ${pace.toFixed(1)}, rating: ${rating.toFixed(1)}, points: ${points.toFixed(1)} }),`;
};
const averagesText = `// GENERATED by scripts/build-euroleague.mjs from scripts/data/euroleague-seasons/ (npm run sync:euroleague-seasons); do not edit.
//
// The EuroLeague's league figures of each earlier season, from the EuroLeague's API: \`pace\` possessions a team a game and
// \`rating\` points per 100 possessions over every game its clubs played (team totals; possessions are field-goal attempts
// + 0.44 free throws - offensive rebounds + turnovers), \`points\` points a team a game in its regular season. A season's
// EuroLeague clubs play at its pace and scoring rate (src/sports/basketball.js euroleagueBasketballIn), as an NBA season's
// franchises play at theirs; \`points\` is what the tests hold it to. The built-in 2026/27 plays ${seasonOf(REFERENCE_SEASON)}'s.
export const EUROLEAGUE_LEAGUE_AVERAGES = Object.freeze({
${earlier.seasons.map(averageRow).join('\n')}
});
`;
const regularShare = club => (club.regular[1] ? club.regular[0] / club.regular[1] : 0);
const movedOf = year => earlier.snapshots[year].players.filter(row => row[7]?.clubs).map(row => `${row[1]}: ${Object.entries(row[7].clubs)
  .map(([club, [games, minutes]]) => `${club} ${games} g ${minutes} min`).join(', ')}, counts for ${row[2]}`);
const seasonsAudit = {
  note: 'Each earlier EuroLeague season as the game plays it (scripts/lib/euroleague-seasons.mjs, docs/design/euroleague.md "Earlier seasons"): '
    + 'the factors its box scores are put on 2025/26\'s level by, its map, its clubs strongest first with their real regular-season record and best '
    + 'five, how well their strengths rank them against those records (Spearman), and its players who played for two clubs. Regenerated by '
    + 'scripts/build-euroleague.mjs.',
  reference: seasonOf(REFERENCE_SEASON),
  seasons: earlier.seasons.map(season => ({
    season: season.season, label: season.label, map: season.map,
    scale: Object.fromEntries(Object.entries(seasonScale(earlier.snapshots, season.year)).map(([key, value]) => [key, Number(value.toFixed(3))])),
    league: earlier.snapshots[season.year].league,
    clubsAgainstRecords: Number(spearman(season.clubs.map(club => club.str), season.clubs.map(regularShare)).toFixed(2)),
    clubs: season.clubs.map(club => ({ id: club.id, name: club.name, str: club.str, regular: `${club.regular[0]}-${club.regular[1] - club.regular[0]}`,
      five: club.squad.map(([name, positions, rating]) => `${name} ${positions} ${rating}`) })),
    moved: movedOf(season.year),
    warnings: season.warnings,
  })),
};
const seasonsAuditText = `${JSON.stringify(seasonsAudit, null, 1)}\n`;

const outputs = new Map([[clubsFile, clubsText], [auditFile, auditText], [averagesFile, averagesText], [seasonsAuditFile, seasonsAuditText]]);
if (check) {
  const differs = [];
  for (const [file, text] of outputs) {
    const current = existsSync(file) ? (await readFile(file, 'utf8')).replace(/\r\n/g, '\n') : null;
    if (current !== text) differs.push(path.relative(root, file));
  }
  if (differs.length) {
    for (const file of differs) console.error(`differs: ${file}`);
    process.exit(1);
  }
  console.log(`Verified the ${clubs.length} EuroLeague clubs, their audit, and the ${earlier.seasons.length} earlier seasons' league figures and audit byte for byte.`);
} else {
  for (const [file, text] of outputs) await writeFile(file, text);
  console.log(`wrote ${[...outputs.keys()].map(file => path.relative(root, file)).join(', ')}`);
}
console.log(`  ${clubs.length} clubs, ${players.length} players on their rosters, ${players.filter(p => p.games).length} with EuroLeague games`);
console.log(`  strongest: ${clubs.slice(0, 5).map(c => `${c.name} ${c.str}`).join(', ')}; weakest: ${clubs.slice(-3).map(c => `${c.name} ${c.str}`).join(', ')}`);
const ratings = clubs.flatMap(c => c.squad.map(p => p[2]));
console.log(`  starters rate ${Math.min(...ratings)}–${Math.max(...ratings)}, ${(ratings.reduce((s, r) => s + r, 0) / ratings.length).toFixed(1)} on average`);
for (const warning of warnings) console.log(`  warning: ${warning}`);
for (const season of earlier.seasons) {
  console.log(`  ${season.season} on ${season.map}: ${season.clubs.length} clubs, strongest ${season.clubs.slice(0, 3).map(c => `${c.name} ${c.str}`).join(', ')}`);
  for (const warning of season.warnings) console.log(`    warning: ${warning}`);
}
