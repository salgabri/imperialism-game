// Build the EuroLeague's clubs from the committed snapshot (scripts/data/euroleague-2026-27.json, npm run sync:euroleague)
// and their identities (scripts/data/euroleague-teams.json): src/data/clubs.euroleague.js, each club with its best five,
// and docs/design/euroleague-audit.json, every rostered player's estimate. Then the earlier seasons' (scripts/data/
// euroleague-seasons/, npm run sync:euroleague-seasons): their league figures, src/data/euroleagueLeagueAverages.js, which
// each season's EuroLeague plays at (src/sports/basketball.js), and docs/design/euroleague-seasons-audit.json, each
// season's clubs, fives and move toward their results (scripts/lib/euroleague-seasons.mjs). The ratings are
// scripts/lib/euroleague-ratings.mjs's, the level the players of scripts/data/euroleague-anchors.json set. The earlier
// seasons' clubs ride in the NBA seasons' files (npm run build:nba-seasons) and play on maps of their own
// (build-europe-maps.mjs).
//
// Usage: node scripts/build-euroleague.mjs [--check]
//   --check  rebuild and compare every file byte for byte; write nothing
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { colourFor } from './lib/club-identity.mjs';
import { euroleagueClubs } from './lib/euroleague.mjs';
import { CLUB_MINUTES, GROUPS, LEVEL, WINDOW, anchorLevel } from './lib/euroleague-ratings.mjs';
import { REFERENCE_SEASON, euroleagueSeasons, seasonScale, spearman } from './lib/euroleague-seasons.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const clubsFile = path.join(root, 'src/data/clubs.euroleague.js');
const auditFile = path.join(root, 'docs/design/euroleague-audit.json');
const averagesFile = path.join(root, 'src/data/euroleagueLeagueAverages.js');
const seasonsAuditFile = path.join(root, 'docs/design/euroleague-seasons-audit.json');
const check = process.argv.includes('--check');
const unknown = process.argv.slice(2).filter(arg => arg !== '--check');
if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);

const snapshot = JSON.parse(await readFile(path.join(root, 'scripts/data/euroleague-2026-27.json'), 'utf8'));
const identity = JSON.parse(await readFile(path.join(root, 'scripts/data/euroleague-teams.json'), 'utf8'));
const anchorsFile = JSON.parse(await readFile(path.join(root, 'scripts/data/euroleague-anchors.json'), 'utf8'));
const teams = Object.fromEntries(Object.entries(identity.clubs).map(([code, team]) => [code, { ...team, col: colourFor(team.id) }]));
// The earlier seasons first: the built-in season's window reads their 2024/25 and 2025/26, and every season shares their
// constants.
const earlier = euroleagueSeasons(root, identity);
const { clubs, players, warnings, groups } = euroleagueClubs(snapshot, teams, identity.names, earlier);
const { source } = snapshot;

const mean = list => list.reduce((sum, x) => sum + x, 0) / list.length;
const fixed = (value, digits = 2) => Number(value.toFixed(digits));
const anchors = anchorsFile.anchors.map(([code, name, edition, nba2k]) => ({ code, name, edition, nba2k }));
// The level the anchors give, every player rated at no level at all: LEVEL is this, to a tenth.
const unshifted = euroleagueClubs(snapshot, teams, identity.names, earlier, { level: 0 }).players;
const level = anchorLevel(anchors, new Map(unshifted.map(p => [p.code, p.exact])));
if (Math.abs(level.level - LEVEL) > 0.05) throw new Error(`The anchors put the level at ${level.level.toFixed(2)}, not LEVEL ${LEVEL}`);

const SOURCE = { name: source.label, retrieved: source.retrieved, url: 'https://www.euroleaguebasketball.net/', api: source.api,
  conversion: `value = w·z(share of the club's minutes) + (1 − w)·z(PIR a minute shrunk toward the fringe's), seasons weighted ${WINDOW.join(':')}; `
    + `rating read off NBA 2K27's starters at the same position group and rank, ${LEVEL} points lower` };
const tuple = ([name, positions, rating, metadata]) => `[${JSON.stringify(name)},'${positions}',${rating},${JSON.stringify(metadata)}]`;
const clubsText = `// GENERATED by scripts/build-euroleague.mjs from scripts/data/euroleague-2026-27.json; do not edit.
//
// The ${clubs.length} clubs of the ${source.label} on their rosters of ${source.retrieved}, each with its best starting five: the
// strongest lineup its players' positions allow. No source rates EuroLeague players, so every rating is the game's
// estimate on NBA 2K's scale from the player's EuroLeague minutes and PIR (${source.seasons.join(', ')}): his value within his
// position group, read off NBA 2K27's starters ${LEVEL} points lower (SOURCE.conversion; scripts/lib/euroleague-ratings.mjs,
// docs/design/euroleague.md), marked as an estimate. A season under way is not moved toward its results. Basketball's
// clubs are the NBA's (src/data/clubs.basketball.js) and these; the two leagues never meet.

export const SOURCE = ${JSON.stringify(SOURCE)};

export const CLUBS = [
${clubs.map(c => `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: 'EuroLeague', country: '${c.country}', col: '${c.col}', str: ${c.str}, squad: [${c.squad.map(tuple).join(',')}] },`).join('\n')}
];
`;

const ruleOf = (constants, own) => Object.fromEntries(GROUPS.map(group => [group, {
  prior: fixed(constants[group].k, 0), typicalMinutes: fixed(constants[group].typical, 0), pairs: constants[group].pairs,
  stability: { selection: fixed(constants[group].selection, 3), production: fixed(constants[group].production, 3) },
  weights: own[group].weights.map(w => fixed(w, 3)), fringePir40: fixed(own[group].replacement * 40, 1),
}]));
const starters = new Set(clubs.flatMap(c => c.squad.map(p => `${c.source}|${p[0]}`)));
const ratingOf = new Map(players.map(p => [p.code, p.rating]));
const audit = {
  note: 'Every player on a EuroLeague roster as the game rates him (scripts/build-euroleague.mjs, scripts/lib/euroleague-ratings.mjs): his share of '
    + 'his clubs\' minutes and his PIR a 40 minutes over the window (shrunk toward the fringe\'s by the prior), the value they blend to within his '
    + 'position group, the rating it reads off NBA 2K27\'s starters at the group (the level\'s points lower), his positions, his EuroLeague games in '
    + 'the window and whether he starts for his club. `rule` gives each group\'s prior (minutes), the stabilities that weigh the blend and the '
    + 'fringe\'s PIR a 40 minutes; `anchors` the players NBA 2K24–2K27 also rated, who set the level. Regenerated with the clubs; the rule is in '
    + 'docs/design/euroleague.md.',
  source: { label: source.label, retrieved: source.retrieved, seasons: source.seasons },
  rule: { window: WINDOW, clubMinutes: CLUB_MINUTES, level: LEVEL, reference: 'NBA 2K27 starters (src/data/clubs.basketball.js) at the group',
    groups: ruleOf(earlier.constants, groups) },
  anchors: { players: level.players, nba2k: fixed(level.nba2k), rated: fixed(mean(anchors.map(a => ratingOf.get(a.code)))),
    level: fixed(level.level), namesakes: anchorsFile.namesakes },
  league: snapshot.league,
  clubs: clubs.map(c => ({ id: c.id, name: c.name, str: c.str, five: c.squad.map(([name, positions, rating]) => `${name} ${positions} ${rating}`) })),
  players: players.slice().sort((a, b) => b.rating - a.rating || b.value - a.value || a.name.localeCompare(b.name))
    .map(p => ({ code: p.code, club: teams[p.club].name, name: p.name, positions: p.positions.join('/'), rating: p.rating, value: fixed(p.value),
      minutes: fixed(p.selection, 3), pir40: fixed(p.production * 40, 1), games: p.games,
      ...(starters.has(`${p.club}|${p.name}`) ? { starts: true } : {}) })),
  warnings,
};
const auditText = `${JSON.stringify(audit, null, 1)}\n`;

// ---------- the earlier seasons ----------

const seasonOf = year => `${year}/${String(year + 1).slice(2)}`;
const averageRow = ({ year }) => {
  const { pace, rating, points } = earlier.snapshots[year].league;
  return `  '${seasonOf(year)}': Object.freeze({ pace: ${pace.toFixed(1)}, rating: ${rating.toFixed(1)}, points: ${points.toFixed(1)} }),`;
};
const averagesText = `// GENERATED by scripts/build-euroleague.mjs from scripts/data/euroleague-seasons/ (npm run sync:euroleague-seasons); do not edit.
//
// The EuroLeague's league figures of each earlier season, from the EuroLeague's API: \`pace\` possessions a team a game and
// \`rating\` points per 100 possessions over every game its clubs played (team totals; possessions are field-goal attempts
// + 0.44 free throws - offensive rebounds + turnovers), \`points\` points a team a game in its regular season. A season's
// EuroLeague clubs play at its pace and scoring rate (src/sports/basketball.js euroleagueBasketballIn), as an NBA season's
// franchises play at theirs; \`points\` is what the tests hold it to. The built-in 2026/27 plays ${seasonOf(REFERENCE_SEASON)}'s.
export const EUROLEAGUE_LEAGUE_AVERAGES = Object.freeze({
${earlier.seasons.map(averageRow).join('\n')}
});
`;
const regularShare = club => (club.regular[1] ? club.regular[0] / club.regular[1] : 0);
const movedOf = year => earlier.snapshots[year].players.filter(row => row[7]?.clubs).map(row => `${row[1]}: ${Object.entries(row[7].clubs)
  .map(([club, [games, minutes]]) => `${club} ${games} g ${minutes} min`).join(', ')}, counts for ${row[2]}`);
const signed = n => (n > 0 ? `+${n}` : String(n));
const seasonsAudit = {
  note: 'Each earlier EuroLeague season as the game plays it (scripts/lib/euroleague-seasons.mjs, docs/design/euroleague.md "Earlier seasons"): '
    + 'the factors its box scores are put on 2025/26\'s level by, its map, its results (the Simple Rating System of every game it played: its '
    + 'reliability, home edge and spread, the margin the engine gives a lineup point at its pace, and the lineup points a point of SRS moves a club, '
    + '√reliability over that), its clubs strongest first with their real regular-season record, their SRS, their move toward it (every player by '
    + 'the first figure, the best few by the second), their engine strength before and after the move and their best five, how well their '
    + 'strengths rank them against those records before and after the move (Spearman), and its players who played for two clubs. Regenerated by '
    + 'scripts/build-euroleague.mjs.',
  reference: seasonOf(REFERENCE_SEASON),
  seasons: earlier.seasons.map(season => ({
    season: season.season, label: season.label, map: season.map,
    scale: Object.fromEntries(Object.entries(seasonScale(earlier.snapshots, season.year)).map(([key, value]) => [key, Number(value.toFixed(3))])),
    league: earlier.snapshots[season.year].league,
    results: { reliability: fixed(season.results.srs.reliability, 3), homeEdge: fixed(season.results.srs.homeEdge, 1), sigma: fixed(season.results.srs.sigma, 1),
      marginPerPoint: fixed(season.results.perPoint, 3), pointsPerMargin: fixed(season.results.scale, 3), mean: fixed(season.results.mean) },
    clubsAgainstRecords: Number(spearman(season.clubs.map(club => club.str), season.clubs.map(regularShare)).toFixed(2)),
    beforeTheMove: Number(spearman(season.clubs.map(club => Math.round(club.move.before)), season.clubs.map(regularShare)).toFixed(2)),
    clubs: season.clubs.map(club => ({ id: club.id, name: club.name, str: club.str, regular: `${club.regular[0]}-${club.regular[1] - club.regular[0]}`,
      srs: fixed(club.move.results, 1), move: `${signed(club.move.shift)}${club.move.plus ? `, best ${club.move.plus} ${signed(club.move.shift + 1)}` : ''}`,
      strength: [fixed(club.move.before, 1), fixed(club.move.after, 1)],
      five: club.squad.map(([name, positions, rating]) => `${name} ${positions} ${rating}`) })),
    moved: movedOf(season.year),
    warnings: season.warnings,
  })),
};
const seasonsAuditText = `${JSON.stringify(seasonsAudit, null, 1)}\n`;

const outputs = new Map([[clubsFile, clubsText], [auditFile, auditText], [averagesFile, averagesText], [seasonsAuditFile, seasonsAuditText]]);
if (check) {
  const differs = [];
  for (const [file, text] of outputs) {
    const current = existsSync(file) ? (await readFile(file, 'utf8')).replace(/\r\n/g, '\n') : null;
    if (current !== text) differs.push(path.relative(root, file));
  }
  if (differs.length) {
    for (const file of differs) console.error(`differs: ${file}`);
    process.exit(1);
  }
  console.log(`Verified the ${clubs.length} EuroLeague clubs, their audit, and the ${earlier.seasons.length} earlier seasons' league figures and audit byte for byte.`);
} else {
  for (const [file, text] of outputs) await writeFile(file, text);
  console.log(`wrote ${[...outputs.keys()].map(file => path.relative(root, file)).join(', ')}`);
}
console.log(`  ${clubs.length} clubs, ${players.length} players on their rosters, ${players.filter(p => p.games).length} with EuroLeague games in the window`);
console.log(`  level ${LEVEL}: the ${level.players} anchors rate ${level.nba2k.toFixed(2)} in NBA 2K, and ${level.level.toFixed(2)} points more at no level`);
console.log(`  strongest: ${clubs.slice(0, 5).map(c => `${c.name} ${c.str}`).join(', ')}; weakest: ${clubs.slice(-3).map(c => `${c.name} ${c.str}`).join(', ')}`);
const ratings = clubs.flatMap(c => c.squad.map(p => p[2]));
console.log(`  starters rate ${Math.min(...ratings)}–${Math.max(...ratings)}, ${mean(ratings).toFixed(1)} on average`);
for (const warning of warnings) console.log(`  warning: ${warning}`);
for (const season of earlier.seasons) {
  const moves = season.clubs.map(club => club.move.shift + club.move.plus / 5);
  console.log(`  ${season.season} on ${season.map}: ${season.clubs.length} clubs, strongest ${season.clubs.slice(0, 3).map(c => `${c.name} ${c.str}`).join(', ')}; `
    + `r ${season.results.srs.reliability.toFixed(2)}, ${season.results.perPoint.toFixed(2)} points a lineup point, moves ${Math.min(...moves).toFixed(1)} to ${signed(Number(Math.max(...moves).toFixed(1)))}`);
  for (const warning of season.warnings) console.log(`    warning: ${warning}`);
}
