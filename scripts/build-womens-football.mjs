// Build women's football's teams from the committed EA SPORTS FC snapshot (scripts/data/ea-fc27-women.csv, npm run
// sync:ea-fc-women): the national XIs (src/data/rosters.womens-football.js), by EA's nationality, and the clubs
// (src/data/clubs.womens-football.js), each with its best XI, as scripts/build-rosters.mjs and scripts/build-clubs.mjs
// build the men's game's.
//
// Nothing here is invented: a nation short of eleven rated players stays short (the game counts each empty shirt at
// 40), and a nation with none fields no team. The five leagues EA licenses whole are theatres of their own; EA's other
// clubs, a club or two of each smaller league, play together as the Rest of Europe.
//
// Usage: node scripts/build-womens-football.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { NATIONS, selectLineup } from '../src/data/teams.js';
import { colourFor, makeCode, slug } from './lib/club-identity.mjs';
import { clubsModule, rostersModule } from './lib/data-module.mjs';
import { loadEaPlayers, NATION_ALIASES, pickFootballSquad, playerTuple } from './lib/football-data.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SPORT = 'womens-football', SIZE = 11;
const source = path.join(root, 'scripts/data/ea-fc27-women.csv');
const rostersFile = path.join(root, 'src/data/rosters.womens-football.js');
const clubsFile = path.join(root, 'src/data/clubs.womens-football.js');
const table = JSON.parse(await readFile(path.join(root, 'scripts/data/ea-women-leagues.json'), 'utf8'));
const leagueOf = new Map(Object.values(table.leagues).map(league => [league.id, league]));

const { players } = await loadEaPlayers(source);
const { edition, snapshotDate } = players[0].sourceInfo;
const mean = xs => xs.reduce((s, x) => s + x, 0) / xs.length;

// ---------- the nations ----------

const nameToId = Object.fromEntries(Object.entries(NATIONS).map(([id, rec]) => [rec[0], id]));
const pools = new Map(), offMap = new Map();
for (const player of players) {
  const id = nameToId[NATION_ALIASES[player.nation] || player.nation];
  if (!id) { offMap.set(player.nation, (offMap.get(player.nation) || 0) + 1); continue; }
  if (!pools.has(id)) pools.set(id, []);
  pools.get(id).push(player);
}
const rosters = {}, names = {};
for (const id of Object.keys(NATIONS)) {
  const pool = pools.get(id);
  if (!pool) continue;
  const squad = pickFootballSquad(pool);
  rosters[id] = [Math.round(selectLineup({ sport: SPORT, squad }).rating), pool.length, squad.map(playerTuple)];
  names[id] = NATIONS[id][0];
}

// ---------- the clubs ----------

const byClub = new Map();
for (const player of players) {
  if (!player.club) throw new Error(`Missing club for ${player.sourceInfo.id}`);
  const league = leagueOf.get(player.leagueId);
  if (!league) throw new Error(`${player.club}: no league ${player.leagueId} in ea-women-leagues.json`);
  if (!byClub.has(player.club)) byClub.set(player.club, { league, players: [] });
  byClub.get(player.club).players.push(player);
}
const taken = new Set();
const clubs = [...byClub.entries()]
  .map(([name, { league, players: pool }]) => {
    const squad = pickFootballSquad(pool);
    return { id: `w-${slug(name)}`, name, league: league.main ? league.name : table.rest, country: league.country,
      str: Math.round(mean(squad.map(player => player.rating))), squad };
  })
  .filter(club => club.squad.length >= SIZE)
  .sort((a, b) => b.str - a.str || a.name.localeCompare(b.name))
  .map(club => {
    const code = makeCode(club.name, taken);
    return { ...club, code, col: colourFor(club.id), squad: club.squad.map(playerTuple) };
  });
if (clubs.length !== byClub.size) throw new Error(`${byClub.size - clubs.length} clubs cannot field eleven`);

// ---------- output ----------

const rostersText = rostersModule(rosters, names, `// GENERATED by scripts/build-womens-football.mjs from the committed ${edition} snapshot (${snapshotDate}); do not edit.
// National teams by EA's nationality, each entry [effective XI strength, rated players of the nation, player tuples].
// Tuples: [display name, primary role, EA overall unchanged, source metadata]. No invented players: a nation short of
// eleven stays short, and a nation with none is not listed and fields no team.
// Stored compactly (scripts/lib/data-module.mjs): each line is JSON, and source
// metadata is a row under a shared shape (src/data/sourceTable.js).
`);
const clubsText = clubsModule(clubs, `// GENERATED by scripts/build-womens-football.mjs from the committed ${edition} snapshot (${snapshotDate}); do not edit.
// Player tuples retain database identity, all natural roles, original overall and source URL.
//
// Every women's club EA SPORTS FC rates, each with its best XI in a 4-4-2 and a strength equal to that lineup's mean
// rating. \`country\` is the map shape the club is seeded from when a club campaign starts.
// Stored compactly: each line is JSON, and source metadata is a row under a shared shape (src/data/sourceTable.js).
`);

if (process.argv.includes('--check')) {
  let differs = false;
  for (const [file, text] of [[rostersFile, rostersText], [clubsFile, clubsText]]) {
    const current = (await readFile(file, 'utf8')).replace(/\r\n/g, '\n');
    if (current !== text) { console.error(`differs: ${path.relative(root, file)}`); differs = true; }
  }
  if (differs) process.exit(1);
  console.log("Verified the women's nations and clubs byte for byte.");
} else {
  await writeFile(rostersFile, rostersText);
  await writeFile(clubsFile, clubsText);
  const entries = Object.entries(rosters);
  const full = entries.filter(([, roster]) => roster[2].length === SIZE);
  console.log(`Wrote ${entries.length} nations to ${path.relative(root, rostersFile)}: ${full.length} full XIs`);
  console.log(`  strongest: ${entries.slice().sort((a, b) => b[1][0] - a[1][0]).slice(0, 8).map(([id, roster]) => `${names[id]} ${roster[0]}`).join(', ')}`);
  console.log(`  short of eleven: ${entries.filter(([, roster]) => roster[2].length < SIZE).map(([id, roster]) => `${names[id]} ${roster[2].length}`).join(', ')}`);
  if (offMap.size) console.log(`  no map nation: ${[...offMap].map(([name, n]) => `${name} ${n}`).join(', ')}`);
  console.log(`Wrote ${clubs.length} clubs to ${path.relative(root, clubsFile)}`);
  for (const league of [...new Set(clubs.map(club => club.league))]) {
    const list = clubs.filter(club => club.league === league);
    console.log(`  ${league}: ${list.length} clubs, ${list[0].name} ${list[0].str} … ${list.at(-1).name} ${list.at(-1).str}`);
  }
}
