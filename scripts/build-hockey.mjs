// Build ice hockey's teams from the committed NHL snapshot (scripts/data/nhl-27.json, npm run sync:nhl): the 32 NHL clubs
// (src/data/clubs.hockey.js, named from scripts/data/nhl-teams.json) and the national teams (src/data/rosters.hockey.js).
// The rules (estimates, lineups, depth, nations) are scripts/lib/nhl.mjs's.
//
// Usage: node scripts/build-hockey.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { colourFor } from './lib/club-identity.mjs';
import { clubsOf, nationsOf, playerOf, ratePlayers, tupleOf } from './lib/nhl.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const clubsFile = path.join(root, 'src/data/clubs.hockey.js');
const rostersFile = path.join(root, 'src/data/rosters.hockey.js');
const snapshot = JSON.parse(await readFile(path.join(root, 'scripts/data/nhl-27.json'), 'utf8'));
const { teams } = JSON.parse(await readFile(path.join(root, 'scripts/data/nhl-teams.json'), 'utf8'));
const { source } = snapshot;

const players = ratePlayers(snapshot.players.map(playerOf));
const clubs = clubsOf(players, teams);
const rosters = nationsOf(players);
const tuple = p => JSON.stringify(tupleOf(p));
const SOURCE = { edition: source.edition, retrieved: source.retrieved, rated: source.rated, floor: source.floor, url: source.ratings };

const clubsText = `// GENERATED by scripts/build-hockey.mjs from scripts/data/nhl-27.json; do not edit.
//
// The 32 NHL clubs on their rosters of ${source.retrieved}, each fielding the lineup the game picks from its whole roster
// (four lines, three pairs and a goalie), then a backup goalie and the best skaters left, up to 23. EA publishes ratings
// for ${source.edition}'s top ${source.rated} only: those are EA's overalls, unchanged, and every other rating is an estimate,
// marked as one (scripts/lib/nhl.mjs).

export const SOURCE = ${JSON.stringify(SOURCE)};

export const CLUBS = [
${clubs.map(c => `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: 'NHL', country: '${teamCountry(c.code)}', col: '${colourFor(c.id)}', str: ${c.str}, squad: [${c.squad.map(tuple).join(',')}] },`).join('\n')}
];
`;
const rostersText = `// GENERATED by scripts/build-hockey.mjs from scripts/data/nhl-27.json; do not edit.
//
// National teams of every NHL roster's players, by EA's nationality for those ${source.edition} rates and by birth
// country for the rest. Each entry is [strength, realCount, squad], where squad is the lineup the game picks from the
// nation's players, then up to a club's depth, and strength counts a place no player of the nation can fill at the
// sport's baseline; the game fields a generated player there. Ratings as in src/data/clubs.hockey.js.

export const ROSTERS = {
${rosters.map(r => `  '${r.id}': [${r.str},${r.squad.length},[${r.squad.map(tuple).join(',')}]], // ${r.name}`).join('\n')}
};
`;

function teamCountry(code) {
  return ['CGY', 'EDM', 'MTL', 'OTT', 'TOR', 'VAN', 'WPG'].includes(code) ? '124' : '840';
}

if (process.argv.includes('--check')) {
  let differs = false;
  for (const [file, text] of [[clubsFile, clubsText], [rostersFile, rostersText]]) {
    const current = (await readFile(file, 'utf8')).replace(/\r\n/g, '\n');
    if (current !== text) { console.error(`differs: ${path.relative(root, file)}`); differs = true; }
  }
  if (differs) process.exit(1);
  console.log('Verified the NHL clubs and the hockey nations byte for byte.');
} else {
  await writeFile(clubsFile, clubsText);
  await writeFile(rostersFile, rostersText);
  const estimatedIn = squad => squad.filter(p => p.estimated).length;
  const clubStarters = clubs.map(c => [c, c.squad]);
  console.log(`Wrote ${clubs.length} NHL clubs to ${path.relative(root, clubsFile)}`);
  console.log(`  strongest: ${clubs.slice(0, 6).map(c => `${c.name} ${c.str}`).join(', ')}`);
  console.log(`  weakest: ${clubs.slice(-4).map(c => `${c.name} ${c.str}`).join(', ')}`);
  console.log(`  squads: ${[...new Set(clubs.map(c => c.squad.length))].join(', ')} players; estimates in a squad: ${Math.min(...clubStarters.map(([, s]) => estimatedIn(s)))} to ${Math.max(...clubStarters.map(([, s]) => estimatedIn(s)))}`);
  console.log(`Wrote ${rosters.length} nations to ${path.relative(root, rostersFile)}`);
  for (const r of rosters) console.log(`  ${r.name} ${r.str}: ${r.squad.length} players, ${estimatedIn(r.squad)} estimated${r.open.length ? `, the game fills ${r.open.join(' ')}` : ''}`);
}
