// Rebuild source-backed national XIs from committed, dated source snapshots.
// Players are persons first (docs/design/football-squad-identity.md): the Reep bridge (scripts/data/reep-bridge.json,
// npm run sync:reep-bridge), then scripts/data/football-identity-overrides.json, then the name matcher key each EA and
// FM record, and each person enters one nation's pool (resolvePersons in scripts/lib/football-data.mjs), so no player
// starts twice in an XI or for two nations.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { HISTORIC_NATIONS, NATIONS, selectLineup } from '../src/data/teams.js';
import { loadFootballData, NATION_ARBITRATION, personKeyOf, pickNationSquads, playerTuple, readIdentityOverrides,
  readReepBridge } from './lib/football-data.mjs';
import { rostersModule } from './lib/data-module.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = process.argv[2] || path.join(root, 'scripts/data/ea-fc27.csv');
const fmSource = process.argv[3] || path.join(root, 'scripts/data/fm26-players.json');
const readJson = async file => JSON.parse(await readFile(path.join(root, file), 'utf8'));
const bridge = readReepBridge(await readJson('scripts/data/reep-bridge.json'));
const overrides = readIdentityOverrides(await readJson('scripts/data/football-identity-overrides.json'));
const data = await loadFootballData(source, fmSource, { bridge, overrides });
const nameToId = Object.fromEntries(Object.entries(NATIONS).map(([id, rec]) => [rec[0], id]));
const label = nation => (nameToId[nation] ? `${nameToId[nation]} ${nation}` : nation);

// One record per person, in the pool of the person's arbitrated nation.
const pools = Object.fromEntries(Object.keys(NATIONS).map(id => [id, []])), unmapped = new Map();
for (const { nation, player } of data.persons) {
  const id = nameToId[nation];
  if (!id) {
    // Off-map nations (Cabo Verde, Malta) land here, but so would a missing alias.
    const row = unmapped.get(nation) || { nationality: nation, players: 0, ea: 0, fm: 0, bestRating: 0 };
    row.players++;
    row[player.sourceInfo.source === 'ea-fc' ? 'ea' : 'fm']++;
    row.bestRating = Math.max(row.bestRating, player.rating);
    unmapped.set(nation, row);
    continue;
  }
  pools[id].push(player);
}
const unmappedNationalities = [...unmapped.values()].sort((a, b) => b.players - a.players || a.nationality.localeCompare(b.nationality));

const picked = pickNationSquads(pools);
const rosters = {}, coverage = [];
for (const [id, rec] of Object.entries(NATIONS)) {
  // Today's season is played on today's map, which has no East Germany or South Vietnam (HISTORIC_NATIONS).
  if (HISTORIC_NATIONS.includes(id)) continue;
  const { pool, squad } = picked[id];
  const lineup = selectLineup({ sport: 'football', squad });
  rosters[id] = [Math.round(lineup.rating), pool.length, squad.map(playerTuple)];
  coverage.push({ id, name: rec[0], players: squad.length,
    ea: squad.filter(p => p.sourceInfo.source === 'ea-fc').length,
    fm: squad.filter(p => p.sourceInfo.source === 'football-manager').length,
    goalkeeper: squad.some(p => p.positions.includes('GK')),
    naturalLineup: lineup.slots.every(slot => slot.player && !slot.outOfPosition),
    // In squad (tuple) order: the Reep id, else the heading record's id.
    personKeys: squad.map(personKeyOf) });
}

const header = `// GENERATED by npm run build-rosters from the committed EA FC / FM snapshots.
// Each entry is [effective XI strength, source pool size, player tuples].
// Tuples: [display name, primary role, game rating, source metadata].
// EA overalls are unchanged. FM source CA (1–100) is scaled once to 1–99;
// its original value, scale, database version and source URL are retained.
// No invented players or confederation-based player ratings. One record per
// real player (Reep person keys, scripts/data/reep-bridge.json), in one nation.
// Stored compactly (scripts/lib/data-module.mjs): each line is JSON, and source
// metadata is a row under a shared shape (src/data/sourceTable.js).
`;
const names = Object.fromEntries(Object.keys(rosters).map(id => [id, NATIONS[id][0]]));
await writeFile(path.join(root, 'src/data/rosters.js'), rostersModule(rosters, names, header));
const eaSnapshots = [...new Map(data.ea.players.map(player => {
  const { edition, update, snapshotDate } = player.sourceInfo;
  return [`${edition}:${update}:${snapshotDate}`, { edition, update, snapshotDate }];
})).values()];

const twin = (ea, fm) => ({
  ea: { id: ea.sourceInfo.id, name: ea.name, fullName: ea.sourceInfo.fullName, nation: label(ea.nation), club: ea.club, dateOfBirth: ea.sourceInfo.dateOfBirth },
  fm: { id: fm.sourceInfo.id, name: fm.name, nation: label(fm.nation), club: fm.club, age: fm.age } });
/** The audit's account of how records became persons (resolvePersons). */
function identityAudit(identity) {
  const { stats } = identity, links = {};
  for (const person of identity.persons) if (person.link) links[person.link] = (links[person.link] || 0) + 1;
  const share = (part, whole) => Math.round(part / whole * 1000) / 10;
  return {
    rule: 'Person key: the Reep id (scripts/data/reep-bridge.json), else a football-identity-overrides.json entry, else the name matcher between records no key pairs yet and no Reep person keeps apart (within a nation by name, then across nations by full name), always with FM\'s age within a year of the EA birth date, one-to-one; an FM name of one word never joins (FM records carry no birth date). A person with no Reep id is keyed by its EA record id, else its FM record id.',
    reep: { release: stats.release, eaRecords: stats.reep.ea, eaShare: share(stats.reep.ea, stats.eaRecords),
      fmRecords: stats.reep.fm, fmShare: share(stats.reep.fm, stats.fmRecords), pairs: stats.reep.pairs },
    overrides: stats.overrides,
    // How each person holding both an EA and an FM record was joined.
    links: Object.fromEntries(Object.entries(links).sort()),
    fallback: { withinNation: stats.fallback.withinNation, omittedAmbiguous: stats.fallback.omittedAmbiguous,
      // FM records of one word with a same-name, same-age EA record: not joined, left out.
      omittedOneWord: stats.fallback.omittedOneWord,
      // Joined across nations: same full name, age within a year, a shared club.
      crossNation: identity.crossNation.map(({ ea, fm }) => ({ personKey: ea.personKey, ...twin(ea, fm) })),
      // Name matches the matcher did not join (reason given): within a nation, 'ages differ' (two people, both kept)
      // and 'one-word FM name' (the FM record left out); across nations, same full name and age kept apart.
      nearMisses: identity.nearMisses.map(({ ea, fm, reason }) => ({ ...twin(ea, fm), reason })) },
    records: { ea: stats.eaRecords, fm: stats.fmRecords }, persons: stats.persons,
  };
}
const nationArbitration = data.identity.arbitration.map(entry => ({ personKey: entry.personKey,
  ea: entry.ea && { id: entry.ea.id, nation: label(entry.ea.nation) }, fm: entry.fm && { id: entry.fm.id, nation: label(entry.fm.nation) },
  chosen: label(entry.chosen), rule: entry.rule }));

const report = { ea: { snapshots: eaSnapshots,
  records: data.ea.rows, excludedFictional: data.ea.fictional, fictionalFilter: data.ea.fictionalFilter }, fm: data.fm,
  fmRecords: data.fmCount,
  // FM records that enter no pool as their own person: joined to a person with an EA record (Reep, override or name
  // match), or left out as ambiguous name matches.
  omittedPossibleDuplicates: data.duplicateCandidates,
  // FM records whose within-nation name match finds exactly one EA record (fuzzy); reep: EA/FM records one Reep id links.
  linking: data.linking,
  identity: identityAudit(data.identity),
  fresherSource: data.fresher,
  nationArbitrationRule: NATION_ARBITRATION,
  nationArbitration,
  unmappedPlayers: unmappedNationalities.reduce((total, row) => total + row.players, 0), unmappedNationalities,
  unknownAbility: data.unknownAbility, conversion: 'round(EFEM currentAbility * 99 / 100)',
  nationalTeams: coverage.length, fullXIs: coverage.filter(r => r.players === 11).length,
  eaShirts: coverage.reduce((total, row) => total + row.ea, 0),
  fmShirts: coverage.reduce((total, row) => total + row.fm, 0), generatedShirts: 0,
  coverage };
// As JSON.stringify(…, null, 2), but arrays of strings or numbers (each XI's person keys, ci95) on one line, and one
// line per entry of the per-person identity logs.
const ONE_LINE_ENTRIES = new Set(['nationArbitration', 'crossNation', 'nearMisses']);
function auditJson(value) {
  const walk = (node, indent, key) => {
    if (node === null || typeof node !== 'object') return JSON.stringify(node);
    const inner = `${indent}  `;
    if (Array.isArray(node)) {
      if (!node.length) return '[]';
      if (node.every(item => item === null || typeof item !== 'object')) return `[${node.map(item => JSON.stringify(item)).join(', ')}]`;
      return `[\n${node.map(item => inner + (ONE_LINE_ENTRIES.has(key) ? JSON.stringify(item) : walk(item, inner))).join(',\n')}\n${indent}]`;
    }
    const entries = Object.entries(node);
    return entries.length ? `{\n${entries.map(([name, item]) => `${inner}${JSON.stringify(name)}: ${walk(item, inner, name)}`).join(',\n')}\n${indent}}` : '{}';
  };
  return `${walk(value, '')}\n`;
}
await writeFile(path.join(root, 'docs/design/football-roster-audit.json'), auditJson(report));
console.log(`National squads: ${report.fullXIs}/${report.nationalTeams} complete XIs; ${report.eaShirts} EA + ${report.fmShirts} FM players; zero generated.`);
const { fictionalFilter } = data.ea;
console.log(`Excluded ${data.ea.fictional} generated EA players: ${fictionalFilter.clubPlayers} at ${fictionalFilter.clubs.length} clubs where at least half the squad is born on 29 February, ${fictionalFilter.clubless.length} clubless; kept ${fictionalFilter.keptRealClubLeapDayBirths} 29-February births at real clubs.`);
const { identity: id, linking } = report;
console.log(`Persons: ${id.persons} from ${id.records.ea} EA + ${id.records.fm} FM records; Reep ${id.reep.release} keys ${id.reep.eaRecords} EA (${id.reep.eaShare}%) and ${id.reep.fmRecords} FM (${id.reep.fmShare}%) records, ${id.reep.pairs} EA–FM pairs; `
  + `overrides ${id.overrides.same} same, ${id.overrides.distinct} distinct, ${id.overrides.nations} nations; name matcher ${id.fallback.withinNation} within nations, ${id.fallback.crossNation.length} across, `
  + `${id.fallback.omittedAmbiguous} ambiguous and ${id.fallback.omittedOneWord} one-word FM records left out, ${id.fallback.nearMisses.length} near misses.`);
console.log(`Linking EA − FM: fuzzy ${linking.meanEaMinusFm} (95% CI ${linking.ci95.join(' to ')}) over ${linking.pairs} pairs; Reep ${linking.reep.meanEaMinusFm} (95% CI ${linking.reep.ci95.join(' to ')}) over ${linking.reep.pairs} pairs.`);
const rules = Object.entries(Object.groupBy(report.nationArbitration, entry => entry.rule)).map(([rule, entries]) => `${entries.length} ${rule}`);
console.log(`Nation conflicts: ${report.nationArbitration.length}${rules.length ? ` (${rules.join(', ')})` : ''}.`);
if (unmappedNationalities.length) {
  console.log(`Skipped ${report.unmappedPlayers} players whose nationality has no map nation (${unmappedNationalities.length} names): `
    + unmappedNationalities.map(row => `${row.nationality} ${row.players}`).join(', '));
}
const incomplete = coverage.filter(row => row.players < 11 || !row.goalkeeper || !row.naturalLineup);
if (incomplete.length) console.log('Coverage requiring attention:', incomplete.map(row => `${row.name} ${row.players}`).join(', '));
