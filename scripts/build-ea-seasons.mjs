// Build the built-in earlier football seasons from EA's FIFA 07 – EA FC 24 rosters (docs/design/football-years.md).
//
//   npm run build:ea-seasons                  writes public/football/ea-*.json, src/data/footballSeasons.js and
//                                             docs/design/football-seasons-audit.json
//   npm run build:ea-seasons -- --check       builds and reports, writes nothing
//   npm run build:ea-seasons -- --data=<dir>  the downloaded sources elsewhere (default data-src/)
//   npm run build:ea-seasons -- --csv=<file>  the FIFA 15 – EA FC 24 export elsewhere (default <data>/ea-leone/male_players.csv)
//
// FIFA 15 – EA FC 24 come from one Kaggle export, FIFA 07 – FIFA 14 from a FIFA Index mirror joined to a SoFIFA scrape
// (scripts/lib/ea-legacy-seasons.mjs). scripts/data/ea-seasons.json names every file with its SHA-256, and the build
// stops on any other file, so every season rebuilds byte for byte.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { EA_COLUMNS, buildEaSeason } from './lib/ea-seasons.mjs';
import { LEGACY_POSITIONS, buildLegacyEaSeason, legacyExclusions, readClubRows, readRatingsRows, rosterDates } from './lib/ea-legacy-seasons.mjs';
import { NATIONS } from '../src/data/teams.js';
import { parseCsv } from './lib/football-data.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sha256Of = bytes => createHash('sha256').update(bytes).digest('hex');

function parseArgs(argv) {
  const args = {};
  for (const arg of argv) {
    const [, key, value] = /^--([a-z]+)(?:=(.*))?$/s.exec(arg) || [];
    if (key === 'check' && value === undefined) args.check = true;
    else if ((key === 'csv' || key === 'data') && value) args[key] = value;
    else throw new Error(`Unknown option ${arg}`);
  }
  return args;
}

/** The export's rows as objects holding only the columns the build reads. */
function readRows(text) {
  const [header, ...rows] = parseCsv(text);
  const at = EA_COLUMNS.map(name => {
    const index = header.indexOf(name);
    if (index < 0) throw new Error(`The export has no "${name}" column`);
    return index;
  });
  return rows.map((row, i) => {
    if (row.length !== header.length) throw new Error(`Row ${i + 2} has ${row.length} fields; expected ${header.length}`);
    return Object.fromEntries(EA_COLUMNS.map((name, k) => [name, row[at[k]]]));
  });
}

/** A source file's text, after checking it is the pinned one. */
async function pinned(file, sha256, what) {
  const bytes = await readFile(file);
  const actual = sha256Of(bytes);
  if (actual !== sha256) throw new Error(`${file} is not the pinned ${what} (SHA-256 ${actual}); see scripts/data/ea-seasons.json`);
  return bytes.toString('utf8');
}

/** FIFA 07 – FIFA 14: each edition's two files joined by EA id (scripts/lib/ea-legacy-seasons.mjs). */
async function buildLegacySeasons(legacy, dataDir) {
  const dates = rosterDates(JSON.parse(await pinned(path.join(dataDir, legacy.dates.file), legacy.dates.sha256, 'roster dates')));
  const exclusions = legacyExclusions(legacy.exclusions);
  const editions = new Set(legacy.editions.map(edition => edition.edition));
  const stray = exclusions.filter(exclusion => !editions.has(exclusion.edition));
  if (stray.length) throw new Error(`Exclusions name editions that are not built: ${[...new Set(stray.map(x => x.edition))].join(', ')}`);
  const results = [];
  for (const edition of legacy.editions) {
    const ratings = readRatingsRows(await pinned(path.join(dataDir, legacy.ratings.folder, edition.ratings.file), edition.ratings.sha256, `${edition.edition} ratings file`));
    const { rows: clubs, duplicates } = readClubRows(await pinned(path.join(dataDir, legacy.clubs.folder, edition.clubs.file), edition.clubs.sha256, `${edition.edition} clubs file`));
    results.push(buildLegacyEaSeason({ ratings, clubs, clubDuplicates: duplicates }, edition,
      { ratingsUrl: legacy.ratings.url, clubsUrl: legacy.clubs.url, dates, exclusions }));
  }
  return results;
}

function listingModule(docs, manifest) {
  const rows = docs.map(doc => `  Object.freeze({ id: '${doc.id}', version: '${doc.version}', year: ${doc.year}, season: '${doc.season}', label: '${doc.label}' }),`);
  return `// GENERATED by npm run build:ea-seasons from EA's FIFA / FC rosters (scripts/data/ea-seasons.json):
// FIFA 15 – EA FC 24: ${manifest.dataset.name}, SHA-256 ${manifest.dataset.sha256.slice(0, 12)}…
// FIFA 07 – FIFA 14: ${manifest.legacy.ratings.name}, joined to ${manifest.legacy.clubs.name}
// The built-in earlier seasons, newest first. Each is public/football/<id>.json, loaded when a setup chooses it
// (src/engine/footballSets.js); docs/design/football-years.md describes them.
export const BUILT_IN_SEASONS = Object.freeze([
${rows.join('\n')}
]);
`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const manifest = JSON.parse(await readFile(path.join(root, 'scripts/data/ea-seasons.json'), 'utf8'));
  const dataDir = path.resolve(args.data ?? path.join(root, 'data-src'));
  const csv = path.resolve(args.csv ?? path.join(dataDir, 'ea-leone', manifest.dataset.file));
  const bytes = await readFile(csv);
  const sha256 = sha256Of(bytes);
  if (sha256 !== manifest.dataset.sha256) {
    throw new Error(`${csv} is not the pinned export (SHA-256 ${sha256}); download ${manifest.dataset.download} and unzip it`);
  }
  const rows = readRows(bytes.toString('utf8'));
  if (rows.length !== manifest.dataset.rows) throw new Error(`The export has ${rows.length} rows, not ${manifest.dataset.rows}`);

  const results = [...manifest.editions.map(edition => buildEaSeason(rows, edition, { dataset: manifest.dataset.url })),
    ...await buildLegacySeasons(manifest.legacy, dataDir)];
  for (const { doc, text, audit } of results) {
    const { coverage } = doc;
    console.log(`${doc.id} ${doc.season} ${doc.label} (${audit.snapshotDate}, ${audit.rows} players): `
      + `${coverage.completeXIs}/${Object.keys(NATIONS).length} full XIs, ${coverage.nations} nations with players, ${coverage.clubs} clubs, ${Math.round(Buffer.byteLength(text) / 1024)} KB`);
    for (const warning of audit.warnings) console.log(`  warning: ${warning}`);
  }
  if (args.check) {
    console.log('Check only, nothing written');
    return;
  }
  for (const { doc, text } of results) await writeFile(path.join(root, 'public/football', `${doc.id}.json`), text);
  await writeFile(path.join(root, 'src/data/footballSeasons.js'), listingModule(results.map(result => result.doc), manifest));
  const { editions, exclusions, ...legacySources } = manifest.legacy;
  const audit = { generatedBy: 'scripts/build-ea-seasons.mjs', dataset: manifest.dataset,
    legacy: { ...legacySources, positions: LEGACY_POSITIONS, exclusions }, seasons: results.map(result => result.audit) };
  await writeFile(path.join(root, 'docs/design/football-seasons-audit.json'), `${JSON.stringify(audit, null, 2)}\n`);
  console.log(`Wrote ${results.length} seasons to public/football/, src/data/footballSeasons.js and docs/design/football-seasons-audit.json`);
}

main().catch(error => {
  console.error(`build-ea-seasons: ${error.message}`);
  process.exitCode = 1;
});
