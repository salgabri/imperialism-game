// Build college football's schools (src/data/clubs.college-football.js) from the committed College Football 27
// snapshot (scripts/data/college-football-27.json, npm run sync:college-football) and the school table
// (scripts/data/cfb-teams.json).
//
// The game's EA SPORTS College Football lists one position per player, as Madden does, and the squad rules are the
// NFL's (scripts/lib/nfl.mjs): its five line spots become OL, the ends and tackles DL, its three linebackers LB, both
// safeties S and the fullback RB; punters have no place in the lineup and are left out. Each school fields the lineup
// the game itself picks from its whole roster (eleven on offence, the nickel defence and the kicker), then the best
// backups at each position. Ratings are EA's overalls, unchanged. A school's league is its conference. A school EA lists
// with no kicker kicks with its best punter.
//
// Usage: node scripts/build-college-football.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { colourFor, playerOf, squadOf, strongestFirst } from './lib/nfl.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const snapshotFile = path.join(root, 'scripts/data/college-football-27.json');
const teamsFile = path.join(root, 'scripts/data/cfb-teams.json');
const outFile = path.join(root, 'src/data/clubs.college-football.js');
const SPORT = 'college-football';

const snapshot = JSON.parse(await readFile(snapshotFile, 'utf8'));
const schools = JSON.parse(await readFile(teamsFile, 'utf8')).teams;
const byEa = new Map(Object.entries(schools).map(([id, team]) => [String(team.ea), { id, ...team }]));
const conferenceOf = new Map(Object.entries(snapshot.conferences).flatMap(([conference, ids]) => ids.map(ea => [String(ea), conference])));
for (const [ea, label] of Object.entries(snapshot.teams)) {
  const team = byEa.get(ea);
  if (!team || team.label !== label) throw new Error(`EA team ${ea} (${label}) is not in cfb-teams.json`);
}
if (byEa.size !== Object.keys(snapshot.teams).length) throw new Error('cfb-teams.json lists a school the snapshot does not have');
const codes = [...byEa.values()].map(team => team.code);
const twice = codes.filter((code, i) => codes.indexOf(code) !== i);
if (twice.length) throw new Error(`Codes used twice: ${twice.join(', ')}`);
const names = [...byEa.values()].map(team => team.name);
if (new Set(names).size !== names.length) throw new Error('Two schools share a name');

const pools = new Map(), punters = new Map();
for (const [, name, ea, listed, overall] of snapshot.players) {
  const player = playerOf(name, listed, overall);
  if (!player) {
    // Punters have no place in the lineup, but a school EA lists with no kicker (Air Force, in the week 10 update) kicks
    // with its best punter.
    if (listed === 'P' && !(punters.get(String(ea))?.rating >= overall)) punters.set(String(ea), { name, pos: 'K', rating: overall });
    continue;
  }
  if (!pools.has(String(ea))) pools.set(String(ea), []);
  pools.get(String(ea)).push(player);
}
const kickedByPunters = [];
for (const [ea, pool] of pools) {
  if (pool.some(player => player.pos === 'K') || !punters.has(ea)) continue;
  pool.push(punters.get(ea));
  kickedByPunters.push(`${snapshot.teams[ea]} (${punters.get(ea).name})`);
}

const clubs = [...byEa.values()].map(team => {
  const { squad, str } = squadOf(pools.get(String(team.ea)) || [], team.name, { sport: SPORT });
  return { id: team.id, name: team.name, code: team.code, league: conferenceOf.get(String(team.ea)), country: '840', col: colourFor(team.id), str, squad };
}).sort(strongestFirst);

const { source } = snapshot;
const text = `// GENERATED by scripts/build-college-football.mjs from scripts/data/college-football-27.json; do not edit.
//
// The ${clubs.length} FBS schools of ${source.edition} (${source.iteration.label}, retrieved ${source.retrieved} from EA SPORTS'
// ratings site), each in its conference. Each fields the lineup the game picks from its whole roster — QB, RB, three WR,
// TE and five OL; four DL, two LB, three CB and two S; the kicker — then its best backups. EA's positions are grouped
// into the game's (its five line spots are OL, ends and tackles DL); ratings are EA's overalls, unchanged.

export const SOURCE = ${JSON.stringify({ edition: source.edition, season: source.season, update: source.iteration.label, retrieved: source.retrieved, url: source.url })};

export const CLUBS = [
${clubs.map(c => `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: ${JSON.stringify(c.league)}, country: '840', col: '${c.col}', str: ${c.str}, squad: [${c.squad.map(p => `[${JSON.stringify(p.name)},'${p.pos}',${p.rating}]`).join(',')}] },`).join('\n')}
];
`;

if (process.argv.includes('--check')) {
  const current = (await readFile(outFile, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== text) { console.error(`differs: ${path.relative(root, outFile)}`); process.exit(1); }
  console.log('Verified the college football schools byte for byte.');
} else {
  await writeFile(outFile, text);
  console.log(`Wrote ${clubs.length} FBS schools to ${path.relative(root, outFile)}`);
  console.log(`  strongest: ${clubs.slice(0, 8).map(c => `${c.name} ${c.str}`).join(', ')}`);
  console.log(`  weakest: ${clubs.slice(-6).map(c => `${c.name} ${c.str}`).join(', ')}`);
  if (kickedByPunters.length) console.log(`  kicking with a punter: ${kickedByPunters.join(', ')}`);
}
