// Build the built-in earlier basketball seasons from 2K Archive's NBA 2K ratings (docs/design/football-years.md), and
// the seasons before NBA 2K from their own sources (the manifest's `extra` with a `format`).
//
//   npm run build:nba-seasons                 writes public/basketball/<id>.json, src/data/basketballSeasons.js and
//                                             docs/design/basketball-seasons-audit.json
//   npm run build:nba-seasons -- --check      builds and compares every output byte for byte, writes nothing
//
// The ratings come from one saved copy of https://2karchive.com/ in data-src/bball-2karchive/home.html, pinned by
// SHA-256 in scripts/data/nba-seasons.json; the build stops on any other copy, so every season rebuilds byte for byte.
// The seasons of the manifest's `extra` come from their own pinned copies in data-src/ (NBA 2K12's list, NBA 2K27's
// MyNBA Eras pages, NBA Live 99's roster files), and each player of the eras and of NBA Live 99 is checked against
// Basketball-Reference's seasons (the manifest's `check`, Sumitro Datta's CC0 copy). Each season names the era map it
// plays on; npm run build:nba-map builds those maps from the same manifest.
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { CLUBS } from '../src/data/clubs.basketball.js';
import { buildNbaSeason, readArchive, readSeasonSources } from './lib/nba-seasons.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function listingModule(docs, manifest) {
  const quoted = text => {
    if (/['\\\n]/.test(text)) throw new Error(`Cannot list ${JSON.stringify(text)}`);
    return `'${text}'`;
  };
  const rows = docs.map(doc => `  Object.freeze({ id: ${quoted(doc.id)}, version: ${quoted(doc.version)}, year: ${doc.year}, season: ${quoted(doc.season)}, label: ${quoted(doc.label)}, map: ${quoted(doc.map)} }),`);
  const extras = Object.entries(manifest.extra || {}).sort(([a], [b]) => Number(a) - Number(b));
  return `// GENERATED by npm run build:nba-seasons from ${manifest.source.name}'s NBA 2K ratings (scripts/data/nba-seasons.json),
// page SHA-256 ${manifest.source.sha256.slice(0, 12)}…${extras.filter(([, source]) => !source.format).map(([, source]) =>
  `, and ${source.edition} from ${source.name}, SHA-256 ${source.sha256.slice(0, 12)}…`).join('')}${extras.filter(([, source]) => source.format).map(([year, source]) =>
  `\n// ${Number(year) - 1}/${year.slice(2)}: ${source.label}, from ${source.name}, SHA-256 ${(source.sha256 ?? source.files.players.sha256).slice(0, 12)}…`).join('')}
// The built-in earlier basketball seasons, newest first: NBA clubs only. Each is public/basketball/<id>.json, loaded
// when a setup chooses it (src/engine/footballSets.js), and plays on its era's map (\`map\`, public/domestic/<map>.json).
export const BUILT_IN_BASKETBALL_SEASONS = Object.freeze([
${rows.join('\n')}
]);
`;
}

async function main() {
  const check = process.argv.includes('--check');
  const unknown = process.argv.slice(2).filter(arg => arg !== '--check');
  if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);
  const { manifest, arenas, years, archived } = await readArchive(root);
  const sources = await readSeasonSources(root, manifest, years);
  const results = manifest.seasons.map(year => {
    const source = sources[String(year)];
    // A season from another source is built from its own players alone; the NBA 2K editions from 2K Archive's table.
    return buildNbaSeason(source ? { [year]: source.players } : years, year, manifest, { arenas, builtIn: CLUBS, archived, source });
  }).sort((a, b) => b.doc.year - a.doc.year);
  for (const { doc, text, audit } of results) {
    console.log(`${doc.id} ${doc.season} ${doc.label} on ${doc.map}: ${doc.clubs.length} clubs from ${audit.rows} players, `
      + `${audit.filledPositions.length} positions filled, ${Math.round(Buffer.byteLength(text) / 1024)} KB; strongest ${doc.clubs.slice(0, 3).map(c => `${c.name} ${c.str}`).join(', ')}`);
    if (audit.sourceRows != null) {
      console.log(`  ${audit.sourceRows} listed, ${audit.kept} kept, ${audit.leftOut.length} left out, ${audit.named.length} named`);
      for (const note of audit.outOfPosition ?? []) console.log(`  out of position: ${note}`);
    }
    for (const warning of audit.warnings) console.log(`  warning: ${warning}`);
  }
  const audit = { generatedBy: 'scripts/build-nba-seasons.mjs', source: manifest.source, extra: manifest.extra, check: manifest.check,
    skipped: manifest.skipped, seasons: results.map(result => result.audit) };
  const outputs = [
    ...results.map(({ doc, text }) => [path.join(root, 'public/basketball', `${doc.id}.json`), text]),
    [path.join(root, 'src/data/basketballSeasons.js'), listingModule(results.map(result => result.doc), manifest)],
    [path.join(root, 'docs/design/basketball-seasons-audit.json'), `${JSON.stringify(audit, null, 2)}\n`],
  ];
  if (check) {
    const differs = [];
    for (const [file, text] of outputs) {
      const current = existsSync(file) ? (await readFile(file, 'utf8')).replace(/\r\n/g, '\n') : null;
      if (current !== text) differs.push(path.relative(root, file));
    }
    if (differs.length) {
      for (const file of differs) console.error(`differs: ${file}`);
      process.exitCode = 1;
      return;
    }
    console.log(`Verified ${results.length} seasons, the listing and the audit byte for byte`);
    return;
  }
  await mkdir(path.join(root, 'public/basketball'), { recursive: true });
  for (const [file, text] of outputs) await writeFile(file, text);
  console.log(`Wrote ${results.length} seasons to public/basketball/, src/data/basketballSeasons.js and docs/design/basketball-seasons-audit.json`);
}

main().catch(error => {
  console.error(`build-nba-seasons: ${error.message}`);
  process.exitCode = 1;
});
