// Build the built-in earlier basketball seasons from 2K Archive's NBA 2K ratings (docs/design/football-years.md), the
// seasons before NBA 2K from their own sources (the manifest's `extra` with a `format`), and the seasons no game rated
// from Basketball-Reference's player seasons (the manifest's `computed`).
//
//   npm run build:nba-seasons                 writes public/basketball/<id>.json, src/data/basketballSeasons.js and
//                                             docs/design/basketball-seasons-audit.json
//   npm run build:nba-seasons -- --check      builds and compares every output byte for byte, writes nothing
//
// The ratings come from one saved copy of https://2karchive.com/ in data-src/bball-2karchive/home.html, pinned by
// SHA-256 in scripts/data/nba-seasons.json; the build stops on any other copy, so every season rebuilds byte for byte.
// The seasons of the manifest's `extra` come from their own pinned copies in data-src/ (NBA 2K12's list, NBA 2K27's
// MyNBA Eras pages, NBA Live 99's roster files), and each player of the eras and of NBA Live 99 is checked against
// Basketball-Reference's seasons (the manifest's `check`, Sumitro Datta's CC0 copy). The computed seasons come from
// the pinned tables of the same copy (data-src/research-gaps/basketball/kaggle-sumitrodatta-v57/): the score is fitted
// again and must be the manifest's, and each season's league averages must be src/data/nbaLeagueAverages.js's. Each
// season names the era map it plays on; npm run build:nba-map builds those maps from the same manifest.
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { CLUBS } from '../src/data/clubs.basketball.js';
import { NBA_LEAGUE_AVERAGES } from '../src/data/nbaLeagueAverages.js';
import { buildNbaSeason, readArchive, readComputedSources, readSeasonSources } from './lib/nba-seasons.mjs';
import { euroleagueSeasons, gameYearOf } from './lib/euroleague-seasons.mjs';
import { contentHash, serializeFootballSet } from '../src/data/footballSetBuild.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

/**
 * A season with the EuroLeague's clubs of its year (2000/01 on) after the NBA's, `euroleague` naming the map they play on
 * (src/data/europeMaps.js), as basketball's built-in clubs are the NBA's and the EuroLeague's. Their players are
 * `[name, positions, rating]` as the NBA's; every rating an estimate from EuroLeague box scores, which the loader marks
 * (src/engine/footballSets.js). The version covers both leagues.
 */
function withEuroleague(result, season) {
  if (!season) return result;
  const clubs = season.clubs.map(({ id, name, code, league, country, col, str, squad }) => ({ id, name, code, league, country, col, str, squad }));
  const doc = {};
  for (const [key, value] of Object.entries(result.doc)) {
    if (key === 'version') doc.version = '';
    else if (key === 'clubs') Object.assign(doc, { euroleague: season.map, clubs: [...value, ...clubs] });
    else if (key === 'coverage') doc.coverage = { players: value.players + clubs.length * 5, clubs: value.clubs + clubs.length };
    else doc[key] = value;
  }
  doc.version = `${doc.id}-${contentHash(doc)}`;
  const audit = { ...result.audit, version: doc.version, euroleague: { map: season.map, clubs: clubs.length } };
  return { ...result, doc, text: serializeFootballSet(doc), audit };
}

function listingModule(docs, manifest) {
  const quoted = text => {
    if (/['\\\n]/.test(text)) throw new Error(`Cannot list ${JSON.stringify(text)}`);
    return `'${text}'`;
  };
  const rows = docs.map(doc => `  Object.freeze({ id: ${quoted(doc.id)}, version: ${quoted(doc.version)}, year: ${doc.year}, season: ${quoted(doc.season)}, label: ${quoted(doc.label)}, map: ${quoted(doc.map)} }),`);
  const extras = Object.entries(manifest.extra || {}).sort(([a], [b]) => Number(a) - Number(b));
  const computed = manifest.computed;
  const season = year => `${year - 1}/${String(year).slice(2)}`;
  return `// GENERATED by npm run build:nba-seasons from ${manifest.source.name}'s NBA 2K ratings (scripts/data/nba-seasons.json),
// page SHA-256 ${manifest.source.sha256.slice(0, 12)}…${extras.filter(([, source]) => !source.format).map(([, source]) =>
  `, and ${source.edition} from ${source.name}, SHA-256 ${source.sha256.slice(0, 12)}…`).join('')}${extras.filter(([, source]) => source.format).map(([year, source]) =>
  `\n// ${Number(year) - 1}/${year.slice(2)}: ${source.label}, from ${source.name}, SHA-256 ${(source.sha256 ?? source.files.players.sha256).slice(0, 12)}…`).join('')}${computed ? `
// ${computed.seasons.length} seasons from ${season(computed.seasons[0])} to ${season(computed.seasons.at(-1))}: ${computed.label}, from ${computed.name},
// Advanced.csv SHA-256 ${computed.files.advanced.sha256.slice(0, 12)}…` : ''}
// The built-in earlier basketball seasons, newest first: clubs only, the NBA's and, from 2000/01, the EuroLeague's of
// that season too. Each is public/basketball/<id>.json, loaded when a setup chooses it (src/engine/footballSets.js); its
// NBA clubs play on its era's map (\`map\`, public/domestic/<map>.json), its EuroLeague clubs on theirs (the file's
// \`euroleague\`, src/data/europeMaps.js).
export const BUILT_IN_BASKETBALL_SEASONS = Object.freeze([
${rows.join('\n')}
]);
`;
}

async function main() {
  const check = process.argv.includes('--check');
  const unknown = process.argv.slice(2).filter(arg => arg !== '--check');
  if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);
  const { manifest, arenas, years, archived } = await readArchive(root);
  const sources = await readSeasonSources(root, manifest, years);
  // The score is fitted on 2K Archive's own table, its NBA 2K12 included.
  const computed = await readComputedSources(root, manifest, { ...years, ...archived }, { arenas, sources, leagueAverages: NBA_LEAGUE_AVERAGES });
  // Each season from 2000/01 carries the EuroLeague's clubs of that season too (scripts/lib/euroleague-seasons.mjs).
  const euroleague = new Map(euroleagueSeasons(root).seasons.map(season => [gameYearOf(season.year), season]));
  const results = manifest.seasons.map(year => {
    const source = sources[String(year)] ?? computed?.seasons[String(year)];
    // A season from another source is built from its own players alone; the NBA 2K editions from 2K Archive's table.
    return withEuroleague(buildNbaSeason(source ? { [year]: source.players } : years, year, manifest, { arenas, builtIn: CLUBS, archived, source }),
      euroleague.get(year));
  }).sort((a, b) => b.doc.year - a.doc.year);
  for (const { doc, text, audit } of results) {
    console.log(`${doc.id} ${doc.season} ${doc.label} on ${doc.map}: ${doc.clubs.length} clubs from ${audit.rows} players, `
      + `${audit.filledPositions.length} positions filled, ${Math.round(Buffer.byteLength(text) / 1024)} KB; strongest ${doc.clubs.slice(0, 3).map(c => `${c.name} ${c.str}`).join(', ')}`);
    if (audit.sourceRows != null) {
      console.log(`  ${audit.sourceRows} listed, ${audit.kept} kept, ${audit.leftOut.length} left out, ${audit.named.length} named`);
    }
    if (audit.population != null) {
      console.log(`  ${audit.population} players by minutes, ${audit.rated} rated, ${audit.noPosition.length} without a position, `
        + `${audit.traded.length} traded; clubs against SRS r = ${audit.clubsAgainstSRS}`);
    }
    for (const note of audit.outOfPosition ?? []) if (audit.sourceRows != null || audit.population != null) console.log(`  out of position: ${note}`);
    for (const warning of audit.warnings) console.log(`  warning: ${warning}`);
  }
  if (computed) {
    const { fit, checks } = computed.summary;
    console.log(`Computed seasons: the score refits on ${fit.pairs} pairs of ${fit.editions} editions (r = ${fit.correlation}); `
      + Object.entries(checks).map(([id, check]) => `${id} ${check.matched} players, Spearman ${check.rankCorrelation}, mean error ${check.meanError}`).join('; '));
  }
  const audit = { generatedBy: 'scripts/build-nba-seasons.mjs', source: manifest.source, extra: manifest.extra, check: manifest.check,
    ...(computed ? { computed: { ...manifest.computed, ...computed.summary } } : {}), skipped: manifest.skipped, seasons: results.map(result => result.audit) };
  const outputs = [
    ...results.map(({ doc, text }) => [path.join(root, 'public/basketball', `${doc.id}.json`), text]),
    [path.join(root, 'src/data/basketballSeasons.js'), listingModule(results.map(result => result.doc), manifest)],
    [path.join(root, 'docs/design/basketball-seasons-audit.json'), `${JSON.stringify(audit, null, 2)}\n`],
  ];
  if (check) {
    const differs = [];
    for (const [file, text] of outputs) {
      const current = existsSync(file) ? (await readFile(file, 'utf8')).replace(/\r\n/g, '\n') : null;
      if (current !== text) differs.push(path.relative(root, file));
    }
    if (differs.length) {
      for (const file of differs) console.error(`differs: ${file}`);
      process.exitCode = 1;
      return;
    }
    console.log(`Verified ${results.length} seasons, the listing and the audit byte for byte`);
    return;
  }
  await mkdir(path.join(root, 'public/basketball'), { recursive: true });
  for (const [file, text] of outputs) await writeFile(file, text);
  console.log(`Wrote ${results.length} seasons to public/basketball/, src/data/basketballSeasons.js and docs/design/basketball-seasons-audit.json`);
}

main().catch(error => {
  console.error(`build-nba-seasons: ${error.message}`);
  process.exitCode = 1;
});
