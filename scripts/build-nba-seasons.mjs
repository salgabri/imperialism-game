// Build the built-in earlier basketball seasons from 2K Archive's NBA 2K ratings (docs/design/football-years.md).
//
//   npm run build:nba-seasons                 writes public/basketball/nba-2k*.json, src/data/basketballSeasons.js and
//                                             docs/design/basketball-seasons-audit.json
//   npm run build:nba-seasons -- --check      builds and reports, writes nothing
//
// The ratings come from one saved copy of https://2karchive.com/ in data-src/bball-2karchive/home.html, pinned by
// SHA-256 in scripts/data/nba-seasons.json; the build stops on any other copy, so every season rebuilds byte for byte.
// Each season names the era map it plays on; npm run build:nba-map builds those maps from the same manifest.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { CLUBS } from '../src/data/clubs.basketball.js';
import { buildNbaSeason, extractYears } from './lib/nba-seasons.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function listingModule(docs, manifest) {
  const rows = docs.map(doc => `  Object.freeze({ id: '${doc.id}', version: '${doc.version}', year: ${doc.year}, season: '${doc.season}', label: '${doc.label}', map: '${doc.map}' }),`);
  return `// GENERATED by npm run build:nba-seasons from ${manifest.source.name}'s NBA 2K ratings (scripts/data/nba-seasons.json),
// page SHA-256 ${manifest.source.sha256.slice(0, 12)}…
// The built-in earlier basketball seasons, newest first: NBA clubs only. Each is public/basketball/<id>.json, loaded
// when a setup chooses it (src/engine/footballSets.js), and plays on its era's map (\`map\`, public/domestic/<map>.json).
export const BUILT_IN_BASKETBALL_SEASONS = Object.freeze([
${rows.join('\n')}
]);
`;
}

async function main() {
  const check = process.argv.includes('--check');
  const unknown = process.argv.slice(2).filter(arg => arg !== '--check');
  if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);
  const manifest = JSON.parse(await readFile(path.join(root, 'scripts/data/nba-seasons.json'), 'utf8'));
  const arenas = JSON.parse(await readFile(path.join(root, 'scripts/data/nba-arenas.json'), 'utf8')).clubs;
  const page = await readFile(path.join(root, 'data-src/bball-2karchive', manifest.source.file));
  const sha256 = createHash('sha256').update(page).digest('hex');
  if (sha256 !== manifest.source.sha256) {
    throw new Error(`data-src/bball-2karchive/${manifest.source.file} is not the pinned copy (SHA-256 ${sha256}); save ${manifest.source.url} there`);
  }
  const years = extractYears(page.toString('utf8'));
  const results = manifest.seasons.map(year => buildNbaSeason(years, year, manifest, { arenas, builtIn: CLUBS }))
    .sort((a, b) => b.doc.year - a.doc.year);
  for (const { doc, text, audit } of results) {
    console.log(`${doc.id} ${doc.season} ${doc.label} on ${doc.map}: ${doc.clubs.length} clubs from ${audit.rows} players, `
      + `${audit.filledPositions.length} positions filled, ${Math.round(Buffer.byteLength(text) / 1024)} KB; strongest ${doc.clubs.slice(0, 3).map(c => `${c.name} ${c.str}`).join(', ')}`);
    for (const warning of audit.warnings) console.log(`  warning: ${warning}`);
  }
  if (check) {
    console.log('Check only, nothing written');
    return;
  }
  await mkdir(path.join(root, 'public/basketball'), { recursive: true });
  for (const { doc, text } of results) await writeFile(path.join(root, 'public/basketball', `${doc.id}.json`), text);
  await writeFile(path.join(root, 'src/data/basketballSeasons.js'), listingModule(results.map(result => result.doc), manifest));
  const audit = { generatedBy: 'scripts/build-nba-seasons.mjs', source: manifest.source, skipped: manifest.skipped,
    seasons: results.map(result => result.audit) };
  await writeFile(path.join(root, 'docs/design/basketball-seasons-audit.json'), `${JSON.stringify(audit, null, 2)}\n`);
  console.log(`Wrote ${results.length} seasons to public/basketball/, src/data/basketballSeasons.js and docs/design/basketball-seasons-audit.json`);
}

main().catch(error => {
  console.error(`build-nba-seasons: ${error.message}`);
  process.exitCode = 1;
});
