// Build Rocket League's national teams from the committed Liquipedia Elo snapshot (scripts/data/rocket-league-elo.json,
// npm run sync:rocket-league) into src/data/rosters.rocket-league.js. The rules (ratings, nations, teams) are
// scripts/lib/rocket-league.mjs's.
//
// Usage: node scripts/build-rocket-league.mjs [--check]
//   npm run build-rocket-league
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { rocketLeague } from '../src/sports/rocketLeague.js';
import { EDITION, LINEUP, MIN_PLAYERS, TEAM_SIZE, leftOut, nationsOf, playerOf, tupleOf } from './lib/rocket-league.mjs';

const args = process.argv.slice(2);
const unknown = args.filter(arg => arg !== '--check');
if (unknown.length) throw new Error(`Unknown option ${unknown[0]}`);
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const snapshotFile = 'scripts/data/rocket-league-elo.json';
const rostersFile = path.join(root, 'src', 'data', 'rosters.rocket-league.js');
const snapshot = JSON.parse(await readFile(path.join(root, snapshotFile), 'utf8'));
const { source } = snapshot;

const players = snapshot.players.map((row, i) => playerOf(row, source.exported, i + 1));
const nations = nationsOf(players, rocketLeague);
const tuple = player => JSON.stringify(tupleOf(player));
const SOURCE = { name: 'Liquipedia', edition: EDITION, license: source.license, updated: source.exported, from: source.from,
  to: source.to, series: source.series, games: source.games, rated: source.rated, url: source.wiki };

const rostersText = `// GENERATED by scripts/build-rocket-league.mjs from ${snapshotFile}; do not edit.
//
// The national teams of Rocket League: every player rated by Elo from the 3v3 series Liquipedia records (${source.from} to
// ${source.to}, ${source.games} games; Liquipedia, CC BY-SA 3.0) who has played in the last ${source.activeDays} days, by the nation
// he last played for in a national-team event, else the flag Liquipedia files him under, each nation's ${TEAM_SIZE} best. A rating is the player's Elo / 25 − 2, rounded
// (scripts/lib/rocket-league.mjs). Each entry is [strength, players, squad]: the strength is the mean of the ${LINEUP} who play,
// and a nation with fewer than ${MIN_PLAYERS} rated players is not here.

export const SOURCE = ${JSON.stringify(SOURCE)};

export const ROSTERS = {
${nations.map(n => `  '${n.id}': [${n.str},${n.squad.length},[${n.squad.map(tuple).join(',')}]], // ${n.name}`).join('\n')}
};
`;

if (args.includes('--check')) {
  const current = (await readFile(rostersFile, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== rostersText) {
    console.error(`differs: ${path.relative(root, rostersFile)}`);
    process.exit(1);
  }
  console.log('Verified the Rocket League nations byte for byte.');
} else {
  await writeFile(rostersFile, rostersText);
  const { noFlag, offMap, short } = leftOut(players);
  console.log(`Wrote ${nations.length} nations to ${path.relative(root, rostersFile)} (Liquipedia Elo, ${source.from} to ${source.to})`);
  for (const n of nations) console.log(`  ${n.name} ${n.str}: ${n.squad.map(p => `${p.name} ${p.rating}`).join(', ')}${n.players > TEAM_SIZE ? ` (+${n.players - TEAM_SIZE})` : ''}`);
  console.log(`  left out: ${noFlag.length} with no flag; ${offMap.length} from a country off the map (${offMap.map(p => `${p.name} ${p.flag}`).join(', ')}); `
    + `${short.length} from a nation of fewer than ${MIN_PLAYERS} (${short.map(p => `${p.name} ${p.flag}`).join(', ')})`);
}
