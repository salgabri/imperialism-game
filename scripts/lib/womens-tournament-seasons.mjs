// A computed women's season (docs/design/womens-football.md, "Computed seasons"): a women's World Cup's or Olympic
// tournament's finalists, each rated from its Elo the day after the final, its XI chosen and ordered by the players'
// records of the tournament, in the data set format the game loads (src/engine/footballSets.js, kinds 'wwc' and 'wol').
// The men's computed World Cup seasons' rule (scripts/lib/world-cup-seasons.mjs) with the women's constants: no I/O,
// every constant the manifest's (scripts/data/womens-tournament-seasons.json), nothing invented: every player is one of
// the tournament's squad, and her rating follows from the nation's Elo and the rule.
import { GREAT_BRITAIN, HOME_NATIONS, NATIONS, selectLineup } from '../../src/data/teams.js';
import { FOOTBALL_FEDERATIONS } from '../../src/data/footballFederations.js';
import {
  FOOTBALL_SET_FORMAT, NO_TEAM, contentHash, dayNationResolver, identitiesFor, nationResolver, serializeFootballSet, territoryFor,
} from '../../src/data/footballSetBuild.js';
import { awardPoints, elevenRatings, orderEleven, pickEleven, seasonOfYear, strengthOf } from './world-cup-seasons.mjs';

export const ATTRIBUTION_FILE = 'public/womens-football/ATTRIBUTION-computed.txt';
/** A season's kind: 'wwc' for a World Cup (the Fjelstul database's tournament id), 'wol' for an Olympic tournament. */
export const kindOf = season => (season.tournament ? 'wwc' : 'wol');
// Each kind's player source, its player ids' prefix, and the tournament's names.
const KINDS = {
  wwc: { source: 'world-cup', prefix: 'wc', name: 'World Cup', short: 'World Cup' },
  wol: { source: 'olympics', prefix: 'ol', name: 'Olympic tournament', short: 'Olympics' },
};

const round2 = x => Math.round(x * 100) / 100;
const plus = x => (x > 0 ? `+${x.toFixed(1)}` : x === 0 ? '0.0' : `−${(-x).toFixed(1)}`);

/** The rule as a season's source names it. */
export function conversionText(manifest, facts, season) {
  const { best, perHundredElo } = manifest.strength;
  const roles = Object.entries(manifest.xi).map(([role, count]) => `${count} ${role}`).join(', ');
  const used = facts.minutes === 'starts' ? 'the most starts, then appearances' : 'the most minutes';
  const order = kindOf(season) === 'wwc' ? 'World Cup awards, goals a minute and minutes'
    : facts.minutes === 'starts' ? 'goals an appearance, starts and appearances' : 'goals a minute and minutes';
  return `T = ${best} − ${perHundredElo} × (E_best − E) / 100, E the nation's Elo on ${facts.elo.date} (the day after the final) and E_best `
    + `the best of the teams active in the four years before (${facts.elo.best.team}, ${facts.elo.best.elo}); the XI (${roles}, ${used}) `
    + `ordered by ${order}; its k-th player T + D_k, D = ${manifest.profile.map(plus).join(', ')}, rounded so the XI sums to round(11 × T)`;
}

/**
 * public/womens-football/ATTRIBUTION-computed.txt: the licence of the season files and the credits the CC BY-SA 4.0 data
 * asks for (author, notice, licence and source links, the changes made), naming every season's version, every
 * Wikipedia revision and every RSSSF page read.
 */
export function attributionText(manifest, docs) {
  const { worldCup, results, crossCheck, wikipedia, rsssf } = manifest.sources;
  const years = kind => manifest.seasons.filter(season => kindOf(season) === kind).map(season => season.tournamentYear);
  const pages = (wikipedia?.pages ?? []).map(page => `    ${page.title}, revision ${page.revision} (https://en.wikipedia.org/w/index.php?oldid=${page.revision})`).join('\n');
  const rsssfPages = (rsssf?.pages ?? []).map(page => `    ${page.heading}, by ${page.author} (${page.url})`).join('\n');
  return `Computed women's football seasons (public/womens-football/wwc-<year>.json, wol-<year>.json)
Generated by scripts/build-womens-tournament-seasons.mjs; do not edit.

Seasons: ${docs.map(doc => doc.version).join(', ')}

These files are licensed under Creative Commons Attribution-ShareAlike 4.0 International (CC BY-SA 4.0,
${worldCup.licenceUrl}), as the data they are derived from asks.
Their ratings are computed by this project, not a game's: each finalist's strength from its Elo the day after the
final, its eleven the players of its squad who played the most, ordered by their records
(docs/design/womens-football.md, "Computed seasons"; scripts/data/womens-tournament-seasons.json).

${worldCup.name}
  ${worldCup.notice}
  ${worldCup.url} (commit ${worldCup.commit})
  Licence: ${worldCup.licence} (${worldCup.licenceUrl})
  Used: the women's World Cups of ${years('wwc').join(', ')}: squads, positions and shirt numbers; appearances, substitutions
  and sendings-off; goals; awards; the players' dates of birth and Wikipedia links.
  Changes: minutes and starts summed per player; each squad reduced to an eleven, ordered and given a computed rating;
  names written given name first.
${pages ? `
Wikipedia (English), by its contributors, ${wikipedia.licence} (${wikipedia.licenceUrl})
  The Olympic tournaments' squads (of ${years('wol').join(', ')}), their goals, and the 2012 tournament's line-ups:
${pages}
  Changes: the squads' positions, shirt numbers, dates of birth and articles kept; goals and line-ups summed per player.
` : ''}${rsssfPages ? `
The Rec.Sport.Soccer Statistics Foundation (RSSSF), ${rsssf.terms}
  The Olympic tournaments' line-ups and substitutions:
${rsssfPages}
  Changes: the line-ups summed into starts, appearances and minutes per player.
` : ''}
${results.name}
  ${results.url} (commit ${results.commit}), ${results.licence}
  Used: every women's full international in it to ${manifest.seasons.reduce((last, season) => Math.max(last, season.tournamentYear), 0)}, rated by the World Football Elo formula eloratings.net publishes.

${crossCheck.name} (${crossCheck.url})
  Served only to check the computed Elo: nothing of theirs is in these files.
`;
}

/**
 * Build one season from its facts and the manifest. Each finalist plays as the game nation its name resolves to in that
 * year; one whose shape the year merges or leaves out stops the build, and so would one that plays as a federation of the
 * day (none does: src/data/namesOfTheDay.js gives women's football its names of the day). Territory is the year's, with
 * only the finalists fielding a side. Great Britain (the 2012 Olympic tournament's) plays on the United Kingdom's shape,
 * as basketball plays it: the home nations' land is its, and it plays under its own name and flag (`identities`).
 * → { doc, text, audit }
 */
export function buildWomensTournamentSeason(facts, manifest, { federations = FOOTBALL_FEDERATIONS } = {}) {
  const { year } = facts;
  const season = manifest.seasons.find(entry => entry.id === facts.id);
  if (!season || season.year !== year) throw new Error(`${facts.id} is not a season of the manifest`);
  const kind = kindOf(season), names = KINDS[kind];
  const resolve = dayNationResolver(nationResolver(manifest.names.nations), federations, year);
  const plain = territoryFor(federations, year);
  const entries = [];
  for (const nation of facts.nations) {
    const id = resolve(nation.team);
    if (id == null || id === NO_TEAM) throw new Error(`${facts.id}: ${nation.team} is no game nation; add it to the manifest's names.nations`);
    if (Object.hasOwn(plain.merged, id) || plain.inactive.includes(id)) throw new Error(`${facts.id}: ${nation.team} (${id}) has no federation of its own in ${seasonOfYear(year)}`);
    if (entries.some(entry => entry.id === id)) throw new Error(`${facts.id}: two finalists are ${NATIONS[id][0]}`);
    entries.push({ id, nation });
  }
  const fielded = new Set(entries.map(entry => entry.id));
  const fields = id => fielded.has(id);
  const territory = territoryFor(federations, year, { fields });
  const ofTheDay = identitiesFor(federations, year, { fields });
  if (Object.keys(ofTheDay).length) throw new Error(`${facts.id}: ${Object.keys(ofTheDay).join(', ')} would play as a federation of the day`);
  const britain = entries.find(entry => entry.id === '826' && manifest.names.codes?.[entry.nation.team] === GREAT_BRITAIN.code);
  if (britain && HOME_NATIONS.some(id => fielded.has(id))) throw new Error(`${facts.id}: Great Britain and a home nation both field a side`);
  if (britain) for (const id of HOME_NATIONS) territory.merged[id] = '826';
  const identities = britain ? { 826: { ...GREAT_BRITAIN } } : null;
  const edition = `${season.tournamentYear} Women's ${names.name}, computed`;

  const nations = {}, nationAudit = [];
  for (const id of Object.keys(NATIONS).filter(fields)) {
    const { nation } = entries.find(entry => entry.id === id);
    const strength = strengthOf(nation.elo, facts.elo.best.elo, manifest.strength);
    const { eleven, filled } = pickEleven(nation.squad, manifest.xi);
    const order = orderEleven(eleven, manifest.awards);
    const ratings = elevenRatings(strength, manifest.profile);
    const players = order.map((player, k) => [player.name, player.position, ratings[k], {
      id: `${names.prefix}:${player.id}`, source: names.source, edition, snapshotDate: facts.elo.date,
      ...(player.wikipedia ? { url: player.wikipedia } : {}),
      team: nation.team, shirt: player.shirt, teamElo: nation.elo, xiRank: k + 1,
      ...(player.minutes != null ? { minutes: player.minutes } : {}), starts: player.starts,
      ...(player.apps != null ? { apps: player.apps } : {}), goals: player.goals,
      ...(player.awards.length ? { awards: player.awards } : {}),
      ...(player.born ? { dateOfBirth: player.born } : {}),
    }]);
    if (new Set(players.map(([name]) => name)).size !== players.length) throw new Error(`${facts.id} ${nation.team}: two players of the XI share a name`);
    const lineup = selectLineup({ sport: 'womens-football', squad: players.map(([name, pos, rating]) => ({ name, pos, rating })) });
    nations[id] = [Math.round(lineup.rating), nation.squad.length, players];
    nationAudit.push({
      id, name: identities?.[id]?.name ?? NATIONS[id][0], team: nation.team, elo: nation.elo, rank: nation.rank, T: round2(strength),
      strength: nations[id][0], mean: round2(ratings.reduce((sum, r) => sum + r, 0) / ratings.length),
      outOfPosition: lineup.slots.filter(slot => slot.outOfPosition).map(slot => `${slot.player.name} (${slot.player.pos} as ${slot.position})`),
      filled: filled.map(player => `${player.name} (${player.position}, ${player.minutes ?? `${player.starts} starts`}${player.minutes != null ? '\'' : ''})`),
      eleven: order.map((player, k) => `${player.name} ${player.position} ${ratings[k]}`
        + `${player.awards.length ? ` ${player.awards.join('/')}` : ''} ${player.goals}g ${player.minutes != null ? `${player.minutes}'` : `${player.starts}s/${player.apps}a`}`),
      awardPoints: order.reduce((sum, player) => sum + awardPoints(player, manifest.awards), 0),
    });
  }
  const all = nationAudit.flatMap(entry => nations[entry.id][2].map(([, , rating]) => ({ T: entry.T, rating })));
  const meanOf = xs => xs.reduce((sum, x) => sum + x, 0) / xs.length;
  const teamVariance = meanOf(all.map(x => x.T ** 2)) - meanOf(all.map(x => x.T)) ** 2;
  const withinVariance = meanOf(all.map(x => (x.rating - x.T) ** 2));
  const coverage = {
    players: all.length, nations: entries.length,
    completeXIs: nationAudit.filter(entry => !entry.outOfPosition.length).length, clubs: 0, leagues: 0,
  };
  const { worldCup, results, wikipedia, rsssf } = manifest.sources;
  const squadsPage = kind === 'wol' ? wikipedia.pages.find(page => page.title === season.squads) : null;
  const doc = {
    format: FOOTBALL_SET_FORMAT, kind, id: facts.id, version: '', year, season: seasonOfYear(year),
    label: `Computed · ${season.tournamentYear} ${names.short}`, local: false,
    source: {
      provider: 'Computed', edition, method: 'computed', computed: true, snapshotDate: facts.elo.date, retrieved: manifest.retrieved,
      url: kind === 'wwc' ? `${worldCup.url}/tree/${worldCup.commit}` : `https://en.wikipedia.org/w/index.php?oldid=${squadsPage.revision}`,
      rawScale: 'Elo', conversion: conversionText(manifest, facts, season),
      licence: manifest.licence, attribution: ATTRIBUTION_FILE,
      ...(kind === 'wwc' ? { squads: { name: worldCup.name, author: worldCup.author, commit: worldCup.commit, licence: worldCup.licence } } : {}),
      results: { name: results.name, commit: results.commit, licence: results.licence },
      ...(kind === 'wol' ? {
        wikipedia: Object.fromEntries([season.squads, ...season.goals, ...season.lineups.filter(source => source.from === 'wikipedia').map(source => source.page)]
          .filter((title, i, list) => list.indexOf(title) === i).map(title => [title, wikipedia.pages.find(page => page.title === title).revision])),
        ...(season.lineups.some(source => source.from === 'rsssf') ? { rsssf: season.lineups.filter(source => source.from === 'rsssf').map(source => source.page) } : {}),
      } : {}),
    },
    nations, clubs: [], territory, ...(identities ? { identities } : {}), coverage,
  };
  doc.version = `${doc.id}-${contentHash(doc)}`;
  const audit = {
    id: doc.id, version: doc.version, season: doc.season, tournament: facts.tournament, elo: facts.elo,
    teamShare: round2(teamVariance / (teamVariance + withinVariance)),
    merged: Object.keys(territory.merged).length, inactive: territory.inactive.length,
    nations: nationAudit.sort((a, b) => b.T - a.T || (a.id < b.id ? -1 : 1)),
  };
  return { doc, text: serializeFootballSet(doc), audit };
}
