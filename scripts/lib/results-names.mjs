const BY_NAME = new Map(Object.entries(RESULTS_NAMES).map(([id, name]) => [name, id]));
const OFF_MAP = new Set(OFF_MAP_RESULTS_NAMES);

/** NATIONS id for a results.csv team name; null for a listed off-map side; undefined for a name in neither list. */
export function nationForResultsName(name) {
  if (BY_NAME.has(name)) return BY_NAME.get(name);
  return OFF_MAP.has(name) ? null : undefined;
}
