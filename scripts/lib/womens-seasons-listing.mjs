// src/data/womensFootballSeasons.js, the listing of every built-in earlier women's football season, written alike by
// scripts/build-womens-seasons.mjs (EA's FIFA / FC seasons) and scripts/build-womens-tournament-seasons.mjs (the computed
// World Cups and Olympic tournaments): each builds its own seasons and reads the other's from public/womens-football/,
// so either run writes the same file.

/** The ids of EA's women's seasons, newest first, as scripts/data/ea-women-seasons.json lists them. */
export const eaWomensSeasonIds = manifest => [...manifest.site, ...manifest.editions].map(edition => edition.id);

/** The ids of the computed women's seasons, as scripts/data/womens-tournament-seasons.json lists them. */
export const womensTournamentSeasonIds = manifest => manifest.seasons.map(season => season.id);

/** The listing module of `docs` (every built-in earlier women's season), newest first. */
export function womensSeasonsModule(docs, { ea, computed }) {
  const sorted = docs.slice().sort((a, b) => b.year - a.year || (a.id < b.id ? 1 : -1));
  const rows = sorted.map(doc => `  Object.freeze({ id: '${doc.id}', version: '${doc.version}', year: ${doc.year}, season: '${doc.season}', label: '${doc.label}' }),`);
  const years = test => computed.seasons.filter(test).map(season => season.tournamentYear).join(', ');
  return `// GENERATED by npm run build:womens-seasons from EA's FIFA / FC rosters (scripts/data/ea-women-seasons.json); do not edit.
${ea.site.map(site => `// ${site.edition}: ${site.name}
`).join('')}${Object.values(ea.exports).map(source => `// ${source.name}, SHA-256 ${source.sha256.slice(0, 12)}…`).join('\n')}
${computed ? `// and by npm run build:womens-tournament-seasons, computed (scripts/data/womens-tournament-seasons.json):
// ${years(season => season.tournament)}: each women's World Cup's finalists, rated from their Elo and their players' records
${computed.seasons.some(season => !season.tournament) ? `// ${years(season => !season.tournament)}: each women's Olympic tournament's alike
` : ''}` : ''}// The built-in earlier women's football seasons, newest first. Each is public/womens-football/<id>.json, loaded when a
// setup chooses it (src/engine/footballSets.js). FIFA 16 to FIFA 22${computed ? ' and the computed seasons' : ''} have national teams only.
export const BUILT_IN_WOMENS_SEASONS = Object.freeze([
${rows.join('\n')}
]);
`;
}
