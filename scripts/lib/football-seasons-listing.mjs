// src/data/footballSeasons.js, the listing of every built-in earlier football season, written alike by
// scripts/build-ea-seasons.mjs (EA's FIFA / FC seasons) and scripts/build-retro-seasons.mjs (the seasons before FIFA 05):
// each builds its own seasons and reads the other's from public/football/, so either run writes the same file.
import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

/** The ids of the EA seasons, newest first, as scripts/data/ea-seasons.json lists them. */
export const eaSeasonIds = manifest => [...manifest.snapshots, ...manifest.site.editions, ...manifest.editions, ...manifest.legacy.editions,
  ...manifest.early.editions].map(edition => edition.id);

/** The ids of the seasons before FIFA 05, newest first, as scripts/data/retro-seasons.json lists them. */
export const retroSeasonIds = manifest => manifest.seasons.map(season => season.id);

/** The ids of the computed World Cup seasons, as scripts/data/world-cup-seasons.json lists them. */
export const worldCupSeasonIds = manifest => manifest.seasons.map(season => season.id);

/** The committed season files of `ids`, read from `dir` (public/football). */
export async function committedSeasons(dir, ids) {
  const docs = [];
  for (const id of ids) {
    const file = path.join(dir, `${id}.json`);
    if (!existsSync(file)) throw new Error(`${file} is missing: build it first`);
    docs.push(JSON.parse(await readFile(file, 'utf8')));
  }
  return docs;
}

/** The listing module of `docs` (every built-in earlier season), newest first. */
export function footballSeasonsModule(docs, { ea, retro, worldCup }) {
  const sorted = docs.slice().sort((a, b) => b.year - a.year || (a.id < b.id ? 1 : -1));
  const rows = sorted.map(doc => `  Object.freeze({ id: '${doc.id}', version: '${doc.version}', year: ${doc.year}, season: '${doc.season}', label: '${doc.label}' }),`);
  return `// GENERATED by npm run build:ea-seasons from EA's FIFA / FC rosters (scripts/data/ea-seasons.json):
${ea.snapshots.map(snapshot => `// ${snapshot.edition}: ${snapshot.name}, SHA-256 ${snapshot.sha256.slice(0, 12)}…\n`).join('')}${
  ea.site.editions.map(edition => `// ${edition.edition}: ${edition.ratings.name}, joined to ${edition.later.name}\n`).join('')}// FIFA 15 – EA FC 24: ${ea.dataset.name}, SHA-256 ${ea.dataset.sha256.slice(0, 12)}…
// FIFA 07 – FIFA 14: ${ea.legacy.ratings.name}, joined to ${ea.legacy.clubs.name}
// FIFA 05, FIFA 06: the same ratings, nations only, with nationalities from the later editions and Wikidata
// and by npm run build:retro-seasons from the databases before them (scripts/data/retro-seasons.json):
${retro.seasons.map(season => `// ${season.season}: ${season.listing}\n`).join('')}${worldCup ? `// and by npm run build:world-cup-seasons, computed (scripts/data/world-cup-seasons.json):
// ${worldCup.seasons.map(season => season.year).join(', ')}: each World Cup's finalists, rated from their Elo and their players' records
` : ''}// The built-in earlier seasons, newest first. Each is public/football/<id>.json, loaded when a setup chooses it
// (src/engine/footballSets.js); docs/design/football-years.md describes them.
export const BUILT_IN_SEASONS = Object.freeze([
${rows.join('\n')}
]);
`;
}
