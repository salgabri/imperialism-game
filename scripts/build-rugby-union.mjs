// Build rugby union's teams from the committed snapshot (scripts/data/rugby-union-2025-26.json, npm run sync:rugby-union):
// the European clubs of 2025/26 (src/data/clubs.rugby-union.js, named from scripts/data/rugby-union-clubs.json) and the
// national teams (src/data/rosters.rugby-union.js), every rating computed by scripts/lib/rugby-union.mjs's method; the
// audit (docs/design/rugby-union-audit.json) records each step's figures.
//
// Usage: node scripts/build-rugby-union.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { colourFor } from './lib/club-identity.mjs';
import { seasonOf, tupleOf } from './lib/rugby-union.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const clubsFile = path.join(root, 'src/data/clubs.rugby-union.js');
const rostersFile = path.join(root, 'src/data/rosters.rugby-union.js');
const auditFile = path.join(root, 'docs/design/rugby-union-audit.json');
const snapshot = JSON.parse(await readFile(path.join(root, 'scripts/data/rugby-union-2025-26.json'), 'utf8'));
const { clubs: specs } = JSON.parse(await readFile(path.join(root, 'scripts/data/rugby-union-clubs.json'), 'utf8'));

const season = seasonOf(snapshot, specs);
const tuple = p => JSON.stringify(tupleOf(p));
const european = season.clubs.filter(club => club.europe !== false);
const SOURCE = { edition: 'Computed', season: '2025/26', provider: 'RugbyPass', url: 'https://www.rugbypass.com/', retrieved: snapshot.source.retrieved };

const clubsText = `// GENERATED by scripts/build-rugby-union.mjs from scripts/data/rugby-union-2025-26.json; do not edit.
//
// Rugby union's ${european.length} European clubs of 2025/26: the Premiership's, the Top 14's and the United Rugby Championship's.
// No game publishes rugby union ratings, so each is computed (docs/design/rugby-union.md): from RugbyPass's team sheets
// and match stats of 2023/24–2025/26, each player's share of his club's minutes, his Test minutes and his production
// (the Six Nations fantasy game's points), weighed by their own stability and ranked within his position, then each
// club moved toward its 2025/26 results. Each fields the matchday 23 the game picks, then its best players left, up to 30.

export const SOURCE = ${JSON.stringify(SOURCE)};

export const CLUBS = [
${european.map(c => `  { id: '${c.id}', name: ${JSON.stringify(c.name)}, code: '${c.code}', league: ${JSON.stringify(c.league)}, country: '${c.country}', col: '${colourFor(c.id)}', str: ${c.str}, squad: [${c.squad.map(tuple).join(',')}] },`).join('\n')}
];
`;
const rostersText = `// GENERATED by scripts/build-rugby-union.mjs from scripts/data/rugby-union-2025-26.json; do not edit.
//
// National teams of rugby union's clubs' players (the Premiership's, the Top 14's and the URC's, South Africa's four
// among them), the ratings as in src/data/clubs.rugby-union.js: each plays for the side he played his latest Test for in
// 2023/24–2025/26. Each entry is [strength, realCount, squad], where squad is the matchday 23 the game picks from the
// nation's players, then up to a club's depth, and strength counts a place no player of the nation can fill at the
// sport's baseline; the game fields a generated player there.

export const ROSTERS = {
${season.nations.map(r => `  '${r.id}': [${r.str},${r.squad.length},[${r.squad.map(tuple).join(',')}]], // ${r.name}`).join('\n')}
};
`;
const audit = {
  about: 'Rugby union 2025/26: each step of the computed ratings (scripts/lib/rugby-union.mjs, docs/design/rugby-union.md).',
  report: season.report,
  clubs: season.clubs.map(c => ({ id: c.id, name: c.name, str: c.str, strength: Math.round(c.strength * 100) / 100, crossing: c.crossing,
    ...season.report.moves[c.rpid] })),
  nations: season.nations.map(n => ({ id: n.id, name: n.name, str: n.str, players: n.squad.length, open: n.open })),
  left: season.left,
};
const auditText = `${JSON.stringify(audit, null, 1)}\n`;

if (process.argv.includes('--check')) {
  let differs = false;
  for (const [file, text] of [[clubsFile, clubsText], [rostersFile, rostersText], [auditFile, auditText]]) {
    const current = (await readFile(file, 'utf8')).replace(/\r\n/g, '\n');
    if (current !== text) { console.error(`differs: ${path.relative(root, file)}`); differs = true; }
  }
  if (differs) process.exit(1);
  console.log('Verified the rugby union clubs, nations and audit byte for byte.');
} else {
  await writeFile(clubsFile, clubsText);
  await writeFile(rostersFile, rostersText);
  await writeFile(auditFile, auditText);
  console.log(`Wrote ${european.length} clubs to ${path.relative(root, clubsFile)} (${season.players.length} players rated, ${season.left.length} left out)`);
  for (const c of season.clubs) {
    const m = season.report.moves[c.rpid];
    console.log(`  ${c.name.padEnd(28)} ${String(c.str).padStart(5)}  SRS ${String(m.srs).padStart(6)}  move ${m.shift >= 0 ? '+' : ''}${m.shift}${m.plus ? ` (+1 for ${m.plus})` : ''}${c.crossing.length ? `  CROSSING ${c.crossing.join(' ')}` : ''}${c.europe === false ? '  (not on the map)' : ''}`);
  }
  console.log(`Wrote ${season.nations.length} nations to ${path.relative(root, rostersFile)}`);
  for (const r of season.nations.slice(0, 30)) console.log(`  ${r.name.padEnd(20)} ${r.str}: ${r.squad.length} players${r.open.length ? `, the game fills ${r.open.join(' ')}` : ''}`);
  console.log(`perPoint ${season.report.perPoint.toFixed(3)}, scale ${season.report.scale.toFixed(4)}, SRS reliability ${season.report.srs.reliability.toFixed(3)}, home edge ${season.report.srs.homeEdge.toFixed(2)}`);
}
